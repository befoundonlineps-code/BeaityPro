// العنصرُ الوحيدُ المسموحُ له أن يطبع رقمًا قد يحمل إشارةً على صفحةٍ عربيّة.
//
// 🔴 **وسببُه مقيسٌ من محرّكٍ حقيقيّ، لا نظريّ:** أوّلُ لقطةٍ لشاشة الجرد رسمت
// `-2` في عمود الشطب على صورة **`2-`**، و`-3` على **`3-`**.
//
// **والآلةُ هي آلةُ `TimeRange` بعينها:** الأرقامُ اللاتينيّةُ صنفُها EN
// **والإشارةُ محايدة**، فتأخذ المحايدةُ اتّجاهَ الفقرة وتقع على الطرف الخطأ.
// ⚠️ **والنصُّ والـDOM سليمان — المقلوبُ هو الرسمُ وحدَه**، فلا تكشفه قراءةُ
// أيّ قيمةٍ ولا أيُّ اختبارٍ يقرأ الشجرة. **يكشفه إنسانٌ ينظر، أو لا يُكشف.**
//
// ⇒ **ولهذا يملكه ملفٌّ واحد.** ستُّ نسخٍ محلّيّةٍ غلطت واحدةً واحدةً قبل أن
// يُبنى `TimeRange`، **وحارسُ `lib/timeRangeDirection.test.js` هو الذي منع
// السابعة — وقد منعني أنا:** كتبتُ `<span dir="ltr">` محلّيًّا داخل شاشة
// الجرد فأسقط الحزمةَ باسمها. **فالمالكُ الثالثُ يُعلَن، ولا يُستثنى موضعٌ.**
//
// ⚠️ **وعلى عنصرٍ سطريٍّ دائمًا** — `dir` على عنصر كتلةٍ يحلّ `text-align:
// start` باتجاه `ltr` ويهرّب المحتوى إلى الطرف الآخر.
//
// ⚠️ **ولا يُلَفُّ به نصٌّ عربيٌّ قويّ** — «بالعبوة: ١٫٣٣» تُرسم صحيحةً لوحدها،
// **والعازلُ يكسرها**. المعزولُ هو الرقمُ وحدَه، والعربيُّ خارجه.
export default function LtrNumber({ children, className }) {
  return <span dir="ltr" className={className}>{children}</span>
}
