-- ٠٩٤ب/ب — القيود. قراءةٌ فقط، **جملةُ `select` واحدة.**
--
-- 🔴 مُجهَّزٌ ولم أشغّله. يُشغَّل بعد ٠٩٤، وآمنٌ في أيِّ وقت.
--
-- ⚠️ **الفئةُ كاملةً ثمّ التصفيةُ بالعين — لا `where conname = '…'`.** سؤالٌ
-- ضيّقٌ عن اسمٍ يرجع صفرًا **سواءٌ غاب القيدُ أو أنشأه بوستجرس باسمٍ آخر**،
-- والمشروعُ دفع ثمنَ هذا أربعَ مرّاتٍ عدّها المراجع.
--
-- المتوقَّع على `stock_lots`: مفتاحٌ أساسيّ · `unique (id, salon_id)` ·
-- ثلاثةُ مفاتيحَ أجنبيّةٍ **مركّبةٍ** (مستودع · منتج · مستند) بـ`(x, salon_id)` ·
-- مفتاحٌ للصالون · و`check (unit_cost >= 0)`.
-- وعلى `stock_movements`: مفتاحٌ أجنبيٌّ **مركَّبٌ** `(lot_id, salon_id)`.
--
-- ⚠️ **وما يُقرأ بالعين هو كلمةُ `(… , salon_id)` في كلّ مفتاح** — مفتاحٌ على
-- `id` وحدَه يمرّ من هذا الاستعلام صامتًا **ويترك البابَ الذي أُنشئ ليُغلق
-- مفتوحًا**، لأن فحصَ التكامل المرجعيِّ يتجاوز RLS دائمًا.
-- ==========================================================================

select
  con.conrelid::regclass::text as on_table,
  con.conname,
  con.contype,
  pg_get_constraintdef(con.oid) as definition
from pg_constraint con
where con.conrelid in (
  'public.stock_lots'::regclass,
  'public.stock_movements'::regclass
)
order by con.conrelid::regclass::text, con.contype, con.conname;
