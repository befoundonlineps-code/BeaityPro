-- 112 -- صلاحيّاتُ `anon` و`authenticated` على كلّ جدول، ومعها حالةُ RLS
--
-- ==========================================================================
-- 🔴 قراءةٌ محضة. لا `create` ولا `alter` ولا `drop` ولا `insert` ولا
--    `update` ولا `delete` ولا `grant` ولا `revoke` — ولا كتلةَ `do`.
--    جملةُ `select` واحدةٌ لا غير، فمحرّرُ Supabase يعرض آخرَ مجموعةِ
--    نتائجَ وحدَها.
--
-- 🔴 والقاعدةُ إنتاجيّةٌ وفيها بياناتُ زبائنَ فعليّين. فهذا الملفُّ **يقيس
--    ولا يعالج**، ولا يصنّف خطرًا: يُخرج الصفوفَ كما هي، ويُقرَّر بعدها.
-- ==========================================================================
--
-- ── ما يجيب عنه ───────────────────────────────────────────────────────────
--
-- ثلاثةُ أعمدةٍ لكلّ جدولٍ في `public`، كما طُلبت:
--   ① الجدول
--   ② الصلاحيّاتُ الممنوحةُ لـ`anon` ولـ`authenticated`، كلٌّ في عمود
--   ③ أ RLS مفعَّلةٌ عليه فعلًا — ومعها عددُ سياساته
--
-- 🔴 و«RLS مفعَّلة» و«له سياسات» شيئان: جدولٌ عليه RLS بلا سياسةٍ واحدة
--    **يمنع الكلَّ**، وجدولٌ له سياساتٌ وRLS مطفأةٌ **لا تُقرأ سياساتُه
--    إطلاقًا**. فيُطبع العمودان معًا، ولا يُشتقّ أحدُهما من الآخر.
--
-- ⚠️ و`relforcerowsecurity` عمودٌ ثالثٌ يُطبع لأنّه يغيّر المعنى: بدونه
--    **مالكُ الجدول يتجاوز RLS**، ومالكُ الجداول هنا هو من يُنشئها.
--
-- ── ⚠️ حدُّ ما يقوله هذا الملفّ، مكتوبًا قبل تشغيله لا بعده ────────────────
--
-- ① **يعدّ جداولَ `public` وحدَها** — `relkind in ('r','p')`. فلا مناظير
--    (`v`) ولا مناظيرُ مُتحقَّقة (`m`) ولا جداولُ أجنبيّة، **ولا مخطَّطاتٌ
--    أخرى** (`auth` · `storage` · `extensions`). ⇒ ومنظورٌ ممنوحٌ عليه
--    `select` لا يظهر هنا، وهو مدًى **لم يُقَس** لا مدًى فارغ.
--
-- ② **ويقرأ ما هو ممنوحٌ مباشرةً للدور المسمّى.** فصلاحيّةٌ تصل `anon`
--    بالوراثة من دورٍ آخرَ قد لا تظهر باسم `anon`. ⇒ فالعمودُ حدٌّ أدنى.
--
-- ③ **ولا يقول شيئًا عن نصّ السياسات.** «عددُ السياسات = ٣» لا يقول
--    ماذا تسمح. وذاك قياسٌ آخر، ولا يُحشر هنا.
--
-- ④ **ولا يقيس ما يفعله المفتاحُ المنشور (`publishable`) فعلًا** — يقيس
--    ما هو مأذونٌ به في القاعدة. والفرقُ بينهما هو RLS نفسُها.
--
-- ── 📌 التوقُّعُ، مُعلَنٌ قبل التشغيل، ومُشتقٌّ من نصّ المستودع لا من الذاكرة ──
--
-- مُشتقٌّ من `docs/sql/094c_revoke_on_the_ledger_tables.sql` وأخواته:
--   · أتوقّع جداولَ يظهر فيها `anon` بلا صلاحيّةٍ («—»)
--   · وأتوقّع أن **لا** يكون كلُّ جدولٍ عليه RLS مفعَّلة
--   ⛔ وأيّ صفٍّ يخالف ذلك خبرٌ، ويُقرأ ولا يُكتَم — ولا يُترجَم حكمًا هنا.
--
-- ⚠️ ولا أُعلن عددًا: لم أُحصِ جداولَ الإنتاج، والعدُّ من النصّ لا يساويها.
--
-- ==========================================================================

select
  c.relname                                                as "الجدول",
  c.relrowsecurity                                         as "RLS مفعَّلة",
  c.relforcerowsecurity                                    as "RLS مفروضةٌ على المالك",
  (select count(*) from pg_policy p where p.polrelid = c.oid)
                                                           as "عددُ السياسات",
  coalesce(
    (select string_agg(distinct g.privilege_type, ', ' order by g.privilege_type)
       from information_schema.role_table_grants g
      where g.table_schema = 'public'
        and g.table_name   = c.relname
        and g.grantee      = 'anon'),
    '—')                                                   as "صلاحيّاتُ anon",
  coalesce(
    (select string_agg(distinct g.privilege_type, ', ' order by g.privilege_type)
       from information_schema.role_table_grants g
      where g.table_schema = 'public'
        and g.table_name   = c.relname
        and g.grantee      = 'authenticated'),
    '—')                                                   as "صلاحيّاتُ authenticated",
  pg_get_userbyid(c.relowner)                              as "المالك"
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public'
  and c.relkind in ('r', 'p')
order by c.relname;
