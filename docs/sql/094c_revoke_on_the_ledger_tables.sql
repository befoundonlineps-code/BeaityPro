-- ==========================================================================
-- ٠٩٤ج — تغييرٌ فقط. لا `select` في هذا الملفّ. والتحقّقُ إعادةُ ٠٩٤ب/ج.
--
-- 🔴 مُجهَّزٌ ولم أشغّله. المالكُ ينفّذه بيده بعد مراجعته.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر، وRLS متجاوَزةٌ هناك** — والمِنَحُ ليست
-- كذلك: **`REVOKE` يمسّ الدورَ لا الصفّ**، فأثرُه يظهر من التطبيق مباشرةً.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- لماذا هذه الثلاثةُ دون الـ٤١
--
-- ADR-054 مقيسٌ ومسجَّل: `anon` و`authenticated` يملكان **السبعَ صلاحيّاتٍ على
-- كلّ جداول `public` بلا استثناء (٤١ جدولًا)**، فـRLS ليست خطَّ الدفاع الأوّل
-- بل الوحيد. **وهذا يبقى صحيحًا عن الثمانية والثلاثين الباقية.**
--
-- 🔴 **والثلاثةُ هنا مختلفةٌ لسببٍ واحدٍ لا غيره: هي سجلٌّ ماليٌّ دائمٌ لا يتغيّر.**
--
--   stock_documents   واقعةٌ وقعت: بضاعةٌ تحرّكت ومالٌ سُجّل
--   stock_movements   الحركةُ نفسُها، وعليها `unit_cost` مختوم
--   stock_lots        الدفعةُ وثمنُها الأصليّ
--
-- **ولا واحدٌ منها يُعدَّل ولا يُحذف — بالتصميم لا بالصدفة.** التصحيحُ عند هذا
-- الموديول **بعكس المستند** (ADR-051): يُكتب مستندٌ ثانٍ يقول إن غلطًا صار
-- وانصحّح، **ولا يُمسّ الأوّل**. فبقاءُ مستندين بدل واحدٍ ميزةٌ لا عيب.
--
-- ⚠️ **وليس السببُ «حسّاسةٌ» ولا «مهمّة» ولا أنها مالٌ فحسب** — `sales` ستكون
-- مالًا أيضًا يومًا. **السببُ أنها لا تُعدَّل أصلًا**: صلاحيّةٌ لفعلٍ لا وجودَ له
-- في أيّ مسار.
--
-- ---------------------------------------------------------------------------
-- ✅ ومقيسٌ أن السحبَ لا يكسر شيئًا
--
--   • **ولا دالّةٍ حيّةٍ تُحدِّث أو تحذف** من الثلاثة. المواضعُ الثلاثةُ الوحيدةُ
--     لـ`update`/`delete` عليها: سكربتُ ترحيلٍ من ٠٤٣ (نُفِّذ ومضى) · ٠٨٩ ·
--     وتنظيفُ ٠٩٤ب/هـ — **وكلُّها تُشغَّل بالمحرّر بدور المالك، والمِنَحُ لا تمسّه.**
--   • **ولا كتابةٍ مباشرةٍ من التطبيق** إلى أيٍّ منها: كلُّ الكتابات عبر `rpc`،
--     والقراءاتُ `select` وحدَها — **و`SELECT` و`INSERT` باقيتان.**
--
-- ⚠️ **والدوالُّ ليست `SECURITY DEFINER`** (مقيسٌ: ٠٥٠ج قاست `prosecdef = false`)،
-- فهي تعمل بصلاحيّة المنادي **وتحتاج `INSERT`** — ولذلك لا تُمسّ.
--
-- ---------------------------------------------------------------------------
-- ⚠️ ولماذا تُسحب الخمسُ لا الاثنتان
--
-- `UPDATE` و`DELETE` هما المقصودان. والثلاثُ الباقياتُ تُسحب معهما **لأن تركَها
-- يترك السؤالَ مفتوحًا**: `TRUNCATE` يفرّغ الجدولَ كلَّه بلا مرورٍ على RLS
-- إطلاقًا — **وهو أخطرُ من `DELETE` لا أقلّ** — و`TRIGGER` يسمح بتعليق منطقٍ
-- على السجلّ، و`REFERENCES` بتثبيت اعتمادٍ عليه من جدولٍ آخر.
--
-- **والمقصدُ أن يبقى المتبقّي قابلًا للقراءة في سطرٍ واحد: `SELECT, INSERT`
-- وانتهى** — لا قائمةٌ يُتذكَّر لماذا نجا كلُّ اسمٍ فيها.
--
-- ⚠️ **و`REVOKE` على صلاحيّةٍ غيرِ ممنوحةٍ لا يفشل**، فالملفُّ قابلٌ للتكرار.
-- ==========================================================================

revoke update, delete, truncate, trigger, references
  on public.stock_lots      from anon, authenticated;

revoke update, delete, truncate, trigger, references
  on public.stock_movements from anon, authenticated;

revoke update, delete, truncate, trigger, references
  on public.stock_documents from anon, authenticated;

-- ⚠️ ويُعاد التأكيدُ على الباقي صراحةً بدل الاعتماد على ما تركه السحب.
--
-- **والسببُ ليس التزيّد:** `GRANT` يضيف ولا يسحب، **و`REVOKE` يسحب ولا يترك
-- بيانًا بما بقي** — فقارئُ هذا الملفِّ بعد سنةٍ يرى ما ذهب ولا يرى ما ظلّ.
-- والسطران أدناه يجعلان الحالةَ المقصودةَ مكتوبةً كاملةً في مكانٍ واحد.
grant select, insert on public.stock_lots      to anon, authenticated;
grant select, insert on public.stock_movements to anon, authenticated;
grant select, insert on public.stock_documents to anon, authenticated;

comment on table public.stock_lots is
  'دفعةُ توريدٍ واحدة: كمّيّةٌ دخلت مستودعًا بثمنٍ معروفٍ في لحظةٍ معروفة. وكلُّ إخراجٍ من المخزون يُختم بثمن دفعته هو لا بمتوسّطٍ ممزوج، وهذا هو الغرض. ⚠️ والصفُّ لا يتغيّر بعد كتابته: المتبقّي منه ليس عمودًا هنا بل مجموعُ حركاته (sum(quantity_base) على lot_id)، لأن الرصيد عند هذا الموديول مجموعُ حركاتٍ لا عمودٌ يُصحَّح. ⚠️ والمنعُ من طبقتين مستقلّتين بعد ٠٩٤ج: لا سياسةَ تعديلٍ ولا حذفٍ (RLS ترفض ما لا سياسةَ له)، ولا منحةَ لهما أصلًا — وهذا استثناءٌ مقصودٌ عن باقي جداول المشروع (ADR-054)، سببُه الوحيد أن هذا الجدول سجلٌّ ماليٌّ دائمٌ لا يُعدَّل، والتصحيحُ فيه بعكس المستند لا بتغيير الصفّ.';
