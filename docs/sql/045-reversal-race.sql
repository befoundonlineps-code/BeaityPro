-- البند ٥١ — سباقُ العكس: فحصٌ قبل القفل، وحارسٌ يُغلقه
--
-- ⚠️ مُجهَّز ومعروض ولا يُشغَّل من طرفي — المالك ينفّذه بمحرّر SQL.
-- ⚠️ مستقلٌّ عن ٠٤٣ و٠٤٤، ولا يحتاج شيئًا منهما ولا يحتاجانه.
-- ⚠️ ولا `RAISE` يُنفَّذ، ولا `do`، ولا جدول مؤقّت. جملةٌ واحدة وثلاث `select`.
-- ✅ ومعادُ التشغيل: `if not exists` تجعل الثانية بلا أثر.
-- ═══════════════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────────────
-- العلّة — مقروءةٌ من ترتيب جمل `reverse_stock_document`
--
--   perform 1 … where reverses_document_id = p_document_id;   ← الفحص
--   if found then raise 'already_reversed';
--   …
--   perform 1 from products … for update;                     ← القفل، بعده
--
-- **والفحص يسبق القفل**، فمعاملتان متزامنتان تقرآن «غير معكوس» معًا وتُدرجان
-- معًا — **فيرتدّ الرصيد ضعف الفرق.**
--
-- ⚠️ **وأشدّ ما فيه أن الموديول بلا علاج:** `cannot_reverse_a_reversal` تمنع
-- عكسَ العكس، وADR-051 يمنع تعديل الصفوف — **فلا يبقى إلا تسوية جرد، وهي
-- الشيء الذي بُني الموديول ليجعلها غير لازمة.**
--
-- ✅ **ولماذا فهرسٌ لا نقلُ القفل فوق الفحص:** نقلُ القفل صحيحٌ اليوم
-- **ويُلغى بإعادة تنظيمٍ تبدو تحسينًا** — وقد فقدنا تعليقًا بهذه الطريقة
-- بالضبط قبل جولات، والحزمة بقيت خضراء. **والفهرس لا يُحذف بإعادة تنظيم، ولا
-- يعتمد على ترتيبٍ يتذكّره أحد.** (وهو «اكتب الشرط لا الترتيب».)
--
-- ✅ و`unique` ببوستجرس يقبل العدم متكرّرًا، **فلا يمسّ المستندات غير العكسية
-- إطلاقًا** — كلّها `NULL` — بلا شرطٍ جزئيّ ولا تعقيد.
-- ───────────────────────────────────────────────────────────────────────────


-- ───────────────────────────────────────────────────────────────────────────
-- ⚠️ يُقرأ قبل الإنشاء — هل بالقاعدة ازدواجٌ قائم أصلًا؟
--
-- إن كان مستندٌ قد عُكس مرّتين فعلًا (بسباقٍ وقع قبل اليوم)، **فجملة الإنشاء
-- ستفشل** — وهذا فشلٌ صحيح لا يُلتفّ عليه: الحارس لا يُركّب فوق حالةٍ يمنعها.
-- **والمتوقَّع: صفر صفوف.** وأي صفٍّ راجع يُقرأ ويُقرَّر قبل المضيّ.
-- ───────────────────────────────────────────────────────────────────────────

select reverses_document_id, count(*) as reversals_of_it
from stock_documents
where reverses_document_id is not null
group by reverses_document_id
having count(*) > 1;


-- ───────────────────────────────────────────────────────────────────────────
-- الحارس
-- ───────────────────────────────────────────────────────────────────────────

create unique index if not exists stock_documents_reverses_document_id_key
  on stock_documents (reverses_document_id);


-- ───────────────────────────────────────────────────────────────────────────
-- التحقّق
-- ───────────────────────────────────────────────────────────────────────────

-- ١. ⚠️ **التعريف يُقرأ، لا الاسم ولا الراية.** فهرسٌ فريد على عمودين يعطي
--    `indisunique = true` **ولا يمنع السباق** — التفرّد حينها على الزوج.
--    **المتوقَّع حرفيًّا: `UNIQUE INDEX … ON public.stock_documents
--    (reverses_document_id)` بعمودٍ واحد.**
select i.relname as index_name,
       ix.indisunique,
       pg_get_indexdef(i.oid) as definition_read_this_not_the_flag
from pg_index ix
join pg_class i on i.oid = ix.indexrelid
join pg_class t on t.oid = ix.indrelid
where t.relname = 'stock_documents'
  and pg_get_indexdef(i.oid) like '%reverses_document_id%';

-- ٢. وواحدٌ فقط — لا نسختان باسمين. **المتوقَّع: ١.**
select count(*) as unique_indexes_on_that_column
from pg_index ix
join pg_class i on i.oid = ix.indexrelid
join pg_class t on t.oid = ix.indrelid
where t.relname = 'stock_documents'
  and ix.indisunique
  and pg_get_indexdef(i.oid) like '%(reverses_document_id)%';

-- ٣. وكل المستندات غير العكسية ما زالت مقبولة — العدمُ المتكرّر لا يُمسّ.
--    **المتوقَّع: عددٌ أكبر من ١، وهو عدد المستندات التي لا تعكس شيئًا.**
select count(*) as documents_with_null_reverses
from stock_documents
where reverses_document_id is null;


