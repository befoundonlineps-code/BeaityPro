-- ==========================================================================
-- ٠٩٢ — قراءةٌ فقط. لا يكتب شيئًا ولا يقدر أن يُسقط تغييرًا.
--
-- 🔴 مُجهَّزٌ ولم أشغّله. آمنٌ في أيِّ وقتٍ وقابلٌ للتكرار.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر، وRLS متجاوَزةٌ هناك** — فما يُقاس هنا
-- شكلُ المخطّط وعددُ الصفوف عبر الصالونات كلِّها، لا العزل.
--
-- ---------------------------------------------------------------------------
-- لماذا وُجد: **الحارسُ اشتغل ولم يره أحد**
--
-- ٠٩٠ب (قسم C) و٠٩١ بلّغا نتيجتَهما بـ`raise notice`، **ولم تصل المالكَ ولا
-- واحدة** — ظهرت له نتيجةُ الجدول الأخيرة وحدَها. فأرقامُ الحرّاس ضاعت
-- والسكربتان اشتغلا. **وحارسٌ اشتغل ولم يره أحدٌ يساوي حارسًا لم يشتغل**،
-- والفرقُ أنك تظنّ أنك قِسْت.
--
-- ⚠️ **ولم يُصحَّح ٠٩٠ب ولا ٠٩١ في مكانهما.** كلاهما نُفِّذ، **والملفُّ هو
-- السجلُّ الوحيد لما لُصق فعلًا** — فالتصحيحُ ينزل بملفٍّ جديد يقرأ الحالة.
--
-- ⚠️ **وما لا يستطيع هذا الملفُّ استرجاعه: `empty_before` من ٠٩١** — كم رأسَ
-- طلبيّةٍ كان موجودًا **قبل** الحذف. ذلك رقمٌ عن لحظةٍ مضت، ولا شيءَ في القاعدة
-- يحمله الآن. **مصدرُه الوحيد مخرَجُ ٠٩١ نفسُه، أو الصفُّ الأخير من مخرَج ٠٨٩**
-- («كم رأسَ طلبيّةٍ بقي بلا سطور»). وهو الرقمُ الذي يحسم سؤالَ «هل وُجدت
-- طلبيّةٌ حقيقيّةٌ يومًا» — لا حالةُ الجدول اليوم.
--
-- المتوقَّع:
--   A  صفٌّ واحد:  invoice_no · text · YES · (بلا افتراضيّ)
--   B  فيه صفٌّ:   product_orders_invoice_no_not_blank_check
--   C  أصفارٌ كلُّها إن كان ٠٩١ قد اكتمل
-- ==========================================================================

-- A · هل نزل عمودُ ٠٩٠.
select
  'A · العمود' as section,
  c.column_name,
  c.data_type,
  c.is_nullable,
  coalesce(c.column_default, '(بلا افتراضيّ)') as column_default
from information_schema.columns c
where c.table_schema = 'public'
  and c.table_name = 'product_orders'
  and c.column_name = 'invoice_no';

-- B · كلُّ قيود الجدول — الفئةُ كاملةً ثمّ التصفيةُ بالعين.
--
-- ⚠️ لا `where conname = '…'`: سؤالٌ ضيّقٌ عن اسمٍ يرجع صفرًا **سواءٌ غاب
-- القيدُ أو كُتب باسمٍ آخر**، والقيدُ الذي يسمّيه بوستجرس لا يُعرف إلّا هكذا.
select
  'B · القيود' as section,
  con.conname,
  con.contype,
  pg_get_constraintdef(con.oid) as definition
from pg_constraint con
where con.conrelid = 'public.product_orders'::regclass
order by con.conname;

-- C · حالةُ الجدول الآن، بالأرقام التي كان ٠٩١ يبلّغها بـ`notice`.
--
-- ⚠️ **وهذه حالةُ اليوم لا شاهدُ ٠٩١.** شاهدُه كان «عددُ الرؤوس التي لها سطور
-- **قبل وبعد**، ولازم يتطابقا» — ومقارنةٌ قبليّةٌ بعديّةٌ لا تُعاد بعد وقوعها.
-- فما يقوله هذا القسمُ هو أن الحالةَ النهائيّة متّسقةٌ مع اكتمال ٠٩١، **لا أن
-- ٠٩١ حذف ما كان يجب وحدَه.**
select
  'C · الحالة الآن' as section,
  count(*) as total_orders,
  count(*) filter (
    where not exists (select 1 from public.product_order_lines l where l.order_id = o.id)
  ) as empty_now_expect_0,
  count(*) filter (
    where exists (select 1 from public.product_order_lines l where l.order_id = o.id)
  ) as with_lines_now,
  (select count(*) from public.product_order_lines) as order_lines_total
from public.product_orders o;
