-- ٠٨٨ — إسقاطُ `product_categories.storage_id`، وإغلاقُ الآليّة المتوازية
--
-- 🔴 هذا الملفُّ يتراجع عن ٠٨٥ — والسجلُّ يقولها بدل أن يتصرّف كأنّ ٠٨٥ لم يقع.
--
-- ٠٨٥ أضاف عمودًا يربط المجلّدَ بمستودعٍ **واحد**. و`storage_categories` — وهو
-- جدولُ ربطٍ متعدّد-لمتعدّد بُني في ٠٦٦أ ومبذورٌ ومحروسٌ بمُشغِّل — كان قائمًا
-- طوال الوقت، **وترويستُه ترفض ذلك العمودَ بالاسم**:
--
--   «neither product_categories.storage_id (refused by a folder in two
--    storages) nor products.storage_id … A junction table, and NEITHER
--    products NOR product_categories is touched at all»
--
-- والرفضُ كان مقيسًا: مستودعٌ ثالثٌ أُشّرت له نفسُ ثلاثة مجلّدات مستودعٍ آخر.
--
-- ⚠️ **ولماذا لم يُرَ:** ٠٨٤ سأل عن **أعمدة `product_categories` وقيودها**،
-- وقيدُ جدول الربط يعيش على **جدول الربط** لا عليها. والسؤالُ الذي يجده هو
-- «مَن **يشير إلى** `product_categories`» — وهو القسم A من ٠٨٧_١ بالحرف. أي
-- أنّ الاستعلامَ الذي كُتب للمسح هو نفسُه الذي كان سيمنع هذا العمود.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 والقيدُ الذي لا يُعبَّر عنه بعمود، وهو سببُ التراجع
-- ═══════════════════════════════════════════════════════════════════════════
--
-- المطلوب: «كلُّ مستودعٍ له أصنافٌ محدَّدةٌ مسموحٌ تكون فيه». وشرطُ نقل البضاعة
-- بين مستودعين أن يحفظ الاثنان **نفسَ المجلّد**.
--
-- وتحت «مجلّد = مستودعٌ واحد» تصير تلك الجملةُ «الوجهةُ = مستودعُه الوحيد»
-- — **أي منعَ كلِّ نقل.** فالقيدُ ليس أصعبَ تعبيرًا بالعمود، هو **مستحيلٌ**
-- به.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ⚠️ ولماذا الآن بالذات
-- ═══════════════════════════════════════════════════════════════════════════
--
-- العمودُ يحمل اليوم ثلاثةَ صفوفٍ كتبها ٠٨٦ب، **ولا سطرَ في التطبيق يقرأه**
-- بعد جولة (ب). فإسقاطُه الآن سطرٌ واحد؛ وإبقاؤه يترك **جوابين لسؤالٍ واحد** —
-- وهي بعينها العلّةُ التي دفعنا ثمنَها هنا: عمودٌ بُني بينما جدولُ الربط قائم.
--
-- ⚠️ **ولا يُعطَّل ولا يُترك فارغًا: يُسقَط.** عمودٌ معطَّلٌ باقٍ هو الآليّةُ
-- الثانية نفسُها بلبوسٍ أهدأ — يقرأه أحدٌ بعد شهر ويظنّه المصدر.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ⚠️ ماذا يذهب معه — ولا يُذكر شيءٌ منه بالاسم
-- ═══════════════════════════════════════════════════════════════════════════
--
-- `DROP COLUMN` يُسقط تلقائيًّا كلَّ ما يعتمد على العمود: المفتاحُ الأجنبيُّ
-- المركّب (٠٨٥)، والفهرسُ عليه، والتعليقُ عليه.
--
-- 🔴 **ولا تُسمّى تلك بالاسم عمدًا** (§4ب): تسميةُ ما نعرفه تفشل **مفتوحةً** —
-- لو كان على العمود شيءٌ رابعٌ لم يخطر (قيدُ `CHECK`، سياسةٌ تذكره، مَنظورٌ)
-- لَما ذكرَته القائمة، **ولَنجح الملفُّ صامتًا عن أنه لم يُسقطه.** أمّا
-- `DROP COLUMN` بلا `CASCADE` فيفشل صاخبًا إن وُجد ما لم يخطر — **وهذا هو
-- المطلوب.**
--
-- ⚠️ **و`CASCADE` ممنوعةٌ هنا لهذا السبب بالضبط:** تجعل «شيءٌ رابعٌ لم يخطر»
-- يُحذف بصمت بدل أن يُبلَّغ عنه.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ⚠️ البند ١: لا استعلامَ تحقّقٍ في هذا الملفّ
-- ═══════════════════════════════════════════════════════════════════════════
--
-- جملةٌ تنفيذيّةٌ واحدة، ولا `select` بعدها. والتحقّقُ في ٠٨٨ب — ملفٌّ مستقلّ،
-- لأن استعلامًا يفشل في هذه المعاملة يُرجع الإسقاطَ ويُبلّغ عن نفسه هو.
--
-- ولا نصَّ عربيًّا يُشحن هنا، فلا قراءةَ راجعةً لازمة.
--
-- ⚠️ **وما لا يُثبته:** `auth.uid()` فاضيةٌ بالمحرّر وRLS متجاوَزةٌ بالكامل.
-- نجاحُ هذا يثبت أن العمودَ ذهب، **ولا يثبت شيئًا عن العزل.**

alter table public.product_categories drop column storage_id;
