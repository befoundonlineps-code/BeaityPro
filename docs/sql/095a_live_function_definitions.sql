-- 🔴 لماذا يسبق ٠٩٥، ولماذا لا يجوز أن يُكتب ٠٩٥ قبله
--
-- ٠٩٥ يعيد كتابة أربع دوالٍّ بـ`CREATE OR REPLACE`. **ورأسُ
-- `docs/db-functions.sql` يقول بالحرف لماذا هذا خطرٌ بلا هذا الملفّ:**
--
--   «`prosrc` بيرجّع الجسم بس، وما بيقول ولا إشي عن `SECURITY DEFINER` ولا
--    `search_path` ولا اللغة. و`CREATE OR REPLACE` بتصفّر كل خاصية ما بتعطيها
--    إياها صراحةً — يعني إعادة بناء دالة من جسمها لحاله **بتسقط تحصيناتها
--    بصمت**. صار فعلًا مع `seed_cancellation_reasons_for_salon`.»
--
-- **فالخطرُ ليس نظريًّا — وقع في هذا المشروع مرّةً بالفعل.**
--
-- ⚠️ **والمصدرُ الذي كنتُ سأبني عنه غيرُ موثوقٍ بإقرارنا نحن:**
--
--   • `docs/db-functions.sql` فيه **١٩ دالّة، ولا واحدةٌ من موديول المخزون** —
--     مقيسٌ ومكتوبٌ برأسه. **«والغائب من هون ما بيثبت إشي عن القاعدة».**
--   • و`docs/sql/README.md` يقول عن ٠٥٦ج إن **«الجسم المنشور متأخّر بتعليق
--     واحد، عمدًا وبإعلان»** — أي أن الملفَّ والقاعدةَ **يُعلَم أنهما مختلفان**.
--
-- ⇒ فإعادةُ البناء عن الملفّات تعني: نسخُ جسمٍ قد يكون متأخّرًا، **وإسقاطُ
-- خصائصَ لا يذكرها الملفُّ أصلًا** — وكلاهما صامت. والدوالُّ الأربعُ تُطلق معًا
-- بلا تدرّج (ADR-051)، **فخطأٌ فيها يُختم على أرقامٍ لا تُستدرَك إلّا بعكس
-- المستند.**
--
-- ---------------------------------------------------------------------------
-- وهذا الملفُّ يفعل شيئين بنفس اللصقة
--
--   ١. **يُخرج النصَّ الحيَّ للأربع** — الأساسُ الذي يُبنى عليه ٠٩٥، بخصائصه
--      كاملةً كما هي في القاعدة لا كما نتذكّرها.
--   ٢. **ويسدّ ثغرةً طلب المالكُ سدَّها:** توثيقُ دوالّ المخزون في
--      `docs/db-functions.sql`. والمخرَجُ يُلصق هناك كما هو.
--
-- ⚠️ **ولسدّ الثغرة كاملةً** (إعادةُ توليد الملفّ بأكمله لا الأربع فقط):
-- **احذف سطرَ `and p.proname in (…)` وحدَه** — يصير الاستعلامُ هو المكتوبَ
-- برأس `db-functions.sql` حرفًا بحرف، ويُلصق مخرَجُه مكان كلّ شيءٍ تحت رأسه.
--
-- ---------------------------------------------------------------------------
-- المتوقَّع
--
--   صفٌّ واحد، فيه نصُّ **أربع** دوالٍّ مفصولةً بسطرين.
--
-- ⚠️ **وإن رجع أقلُّ من أربع، فذلك خبرٌ لا نقصٌ في الاستعلام:** يعني أن اسمًا
-- منها ليس كما نظنّ — **وهو بالضبط الصنفُ الذي كلّف هذا المشروعَ أربعَ مرّات**
-- (`reversed_document_id` مقابل `reverses_document_id` بحرفين). **والعدُّ يُقرأ
-- قبل النصّ.**
--
-- ⚠️ **وشرطُ `pg_depend` منسوخٌ من الاستعلام الأصليّ ولا يُحذف:** يستثني دوالَّ
-- الامتدادات، وبدونه تغرق الأربعُ بين ١٢٦ دالّةَ `gbt_*` من `btree_gist`.
-- ==========================================================================

select
  count(*)                                                              as functions_found_expect_4,
  string_agg(pg_get_functiondef(p.oid), E'\n\n' order by p.proname)     as definitions
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public'
  and p.prokind in ('f', 'p')
  and not exists (
    select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e'
  )
  and p.proname in (
    'post_stock_document',
    'transfer_stock',
    'post_stocktake_session',
    'reverse_stock_document'
  );
