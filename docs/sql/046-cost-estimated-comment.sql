-- تصحيح وصف العمود `cost_is_estimated` — وصفٌ **موجودٌ بالقاعدة الآن** وخاطئ
--
-- ⚠️ مُجهَّز ومعروض ولا يُشغَّل من طرفي — المالك ينفّذه بمحرّر SQL.
-- ⚠️ جملةٌ واحدة و`select` للتحقّق. لا DDL بنيوي، ولا `raise`، ولا `do`.
-- ✅ ومعاد التشغيل بلا أثر.
-- ═══════════════════════════════════════════════════════════════════════════

-- ───────────────────────────────────────────────────────────────────────────
-- ما الخطأ
--
-- الوصف المُودَع بسكربت ٠٤٣ يقول:
--
--   «صحيح حين اشتُقّت التكلفة من السلسلة بدل أن يُمليها إنسان»
--
-- **وهو خاطئ، وانكشف بأول جرد حقيقي.** سطران بنفس مستند الجرد:
--
--   شامبو (نقص)  quantity_base -2  unit_cost 50  cost_is_estimated **false**
--   باكيج (فائض) quantity_base +5  unit_cost  0  cost_is_estimated **true**
--
-- كلاهما `doc_type = stocktake` — **فلا قاعدةٌ مصوغةٌ بنوع المستند تفسّرهما.**
--
-- ✅ **والسلوك سليم، والوصف وحده هو الناقص.** فالإسناد بالدوالّ الثلاث هو
-- حرفيًّا نفيُ الدرجة ١:
--
--   v_estimated := (v_balance <= 0);
--   if not v_estimated then   -- الدرجة ١: متوسّط مرجّح من حركات هذا المستودع
--
-- فالشامبو له رصيدٌ موجب ⇒ الدرجة ١ ⇒ `false`، **رغم أن الدرجة ١ مشتقّة**.
-- والباكيج لم يتحرّك قطّ ⇒ نزلت السلسلة إلى الصفر ⇒ `true`.
--
-- ⚠️ **وثلاث طرقٍ إلى `false` لا واحدة**: سعرٌ أملاه إنسان (توريد/افتتاح، ولا
-- سلسلة تُستدعى أصلًا) · الدرجة ١ نفسها · ونسخًا حين يعكس مستندٌ حركةً.
--
-- **والجملة الجامعة التي تُحفظ:** الرقم إمّا ثمنٌ دُفع فعلًا، أو متوسّط أثمانٍ
-- دُفعت فعلًا لبضاعةٍ موجودةٍ هنا. وما عداه بديلٌ عن ثمنٍ لم يستطع هذا
-- المستودع أن يقدّمه — وهو وحده ما يُوسَم.
--
-- ⚠️ ولماذا سكربتٌ مستقلّ: **الوصف الخاطئ مُودَعٌ فعلًا**، وتصحيحُه بالملف
-- وحده يترك القاعدة تقول شيئًا والمستودع يقول غيره. ومن يقرأ الوصف القديم
-- ويعدّل السلسلة يظنّ الدرجة ١ موسومة.
-- ───────────────────────────────────────────────────────────────────────────

comment on column stock_movements.cost_is_estimated is
  'صحيح حين نزلت سلسلة التكلفة تحت درجتها الأولى: أي حين لم يكن بهذا المستودع رصيدٌ موجب يُشتقّ منه متوسّط، فأُخذ الرقم من آخر وارد أو من مستودعٍ آخر أو من السعر الاسميّ أو انتهى صفرًا (الدرجات ٢–٥). وكاذب بثلاث طرق: سعرٌ أملاه إنسان بالتوريد أو الافتتاح (لا سلسلة أصلًا)، أو الدرجة ١ نفسها (متوسّط مرجّح من حركات حقيقية موجودة هنا)، أو نسخًا عن حركةٍ يعكسها مستند. علامة دائمة: لا نعيد حساب تكلفة مختومة (ADR-051).';


-- ───────────────────────────────────────────────────────────────────────────
-- التحقّق — النصّ يُقرأ، لا وجود العمود
-- ───────────────────────────────────────────────────────────────────────────

-- ١. **المتوقَّع: أن يبدأ بـ«صحيح حين نزلت سلسلة التكلفة تحت درجتها الأولى».**
select col_description('public.stock_movements'::regclass, a.attnum) as comment
from pg_attribute a
where a.attrelid = 'public.stock_movements'::regclass
  and a.attname = 'cost_is_estimated';

-- ٢. ⚠️ والسطران اللذان كشفا الخطأ — يُقرآن معًا لأن الفرق بينهما هو القاعدة.
--    **المتوقَّع: صفٌّ بـ`false` وله متوسّط، وصفٌّ بـ`true` بلا متوسّط** —
--    وكلاهما من مستند جرد، فلا نوع المستند يفرّق بينهما.
select m.product_id, d.doc_type, m.quantity_base, m.unit_cost, m.cost_is_estimated,
       b.balance_base, b.avg_cost
from stock_movements m
join stock_documents d on d.id = m.document_id
left join product_balances b
       on b.storage_id = m.storage_id and b.product_id = m.product_id
where d.doc_type = 'stocktake'
order by m.created_at, m.id;
