-- ==========================================================================
-- ٠٩٤ب/ج — العزل: السياساتُ والمنَح. قراءةٌ فقط، **جملةُ `select` واحدة.**
--
-- 🔴 مُجهَّزٌ ولم أشغّله. يُشغَّل بعد ٠٩٤، وآمنٌ في أيِّ وقت.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر وRLS متجاوَزة** — فهذا يقيس **وجودَ
-- السياسات ونصَّها**، لا أنها تعزل فعلًا. العزلُ لا يظهر إلّا من التطبيق
-- بجلسةٍ حقيقيّة، **ويُقال هنا كي لا يُقرأ المخرَجُ على أنه أثبت الاثنين.**
--
-- ---------------------------------------------------------------------------
-- المتوقَّع، وهو **غيابٌ** بقدر ما هو حضور
--
--   السياسات:  `select` و`insert` فقط — **صفرُ `update` وصفرُ `delete`**
--   المنَح:    `SELECT` و`INSERT` لـ`authenticated` — ولا `UPDATE`/`DELETE`
--
-- 🔴 **والدفعةُ لا تتغيّر بعد كتابتها**: المتبقّي منها مشتقٌّ لا مخزَّن، وما بقي
-- حقائقُ عن واقعةٍ وقعت. فوجودُ `update` أو `delete` هنا **خطأٌ لا تشدّدٌ ناقص**،
-- والمنعُ مقصودٌ من طبقتين: السياسةُ تُصفّي الصفوف، **والمنحةُ تقرّر إن كان
-- الدورُ يلمس الجدولَ من الأساس.**
--
-- ⚠️ **ووجودُ `anon` بين المستفيدين متوقَّعٌ ولا يُقرأ ثغرة:** امتيازاتُ Supabase
-- الافتراضيّةُ على `public` تمنحه، **وRLS هي الطبقةُ الوحيدة** هنا لا الثانية —
-- وهذا مسجَّلٌ بـADR-054 منذ ٠٥٣ب.
-- ==========================================================================

select 'سياسة' as kind, p.policyname as name, p.cmd as detail,
       coalesce(p.qual, '—') as using_clause,
       coalesce(p.with_check, '—') as check_clause
from pg_policies p
where p.schemaname = 'public' and p.tablename = 'stock_lots'

union all

select 'منحة', g.grantee, g.privilege_type, '—', '—'
from information_schema.role_table_grants g
where g.table_schema = 'public' and g.table_name = 'stock_lots'

order by kind, name, detail;
