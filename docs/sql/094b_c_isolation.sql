-- ==========================================================================
-- ٠٩٤ب/ج — العزل: السياساتُ والمنَح. قراءةٌ فقط، **جملةُ `select` واحدة.**
--
-- 🔴 مُجهَّزٌ ولم أشغّله. يُشغَّل بعد ٠٩٤، وآمنٌ في أيِّ وقت.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر وRLS متجاوَزة** — فهذا يقيس **وجودَ
-- السياسات ونصَّها**، لا أنها تعزل فعلًا. العزلُ لا يظهر إلّا من التطبيق
-- بجلسةٍ حقيقيّة، **ويُقال هنا كي لا يُقرأ المخرَجُ على أنه أثبت الاثنين.**
--
-- ---------------------------------------------------------------------------
-- المتوقَّع، وهو **غيابٌ** بقدر ما هو حضور
--
--   السياسات:  `select` و`insert` فقط — **صفرُ `update` وصفرُ `delete`**
--   المنَح:    `SELECT` و`INSERT` لـ`authenticated` — ولا `UPDATE`/`DELETE`
--
-- 🔴 **والدفعةُ لا تتغيّر بعد كتابتها**: المتبقّي منها مشتقٌّ لا مخزَّن، وما بقي
-- حقائقُ عن واقعةٍ وقعت. فوجودُ `update` أو `delete` هنا **خطأٌ لا تشدّدٌ ناقص**،
-- والمنعُ مقصودٌ من طبقتين: السياسةُ تُصفّي الصفوف، **والمنحةُ تقرّر إن كان
-- الدورُ يلمس الجدولَ من الأساس.**
--
-- ⚠️ **ووجودُ `anon` بين المستفيدين متوقَّعٌ ولا يُقرأ ثغرة:** امتيازاتُ Supabase
-- الافتراضيّةُ على `public` تمنحه، **وRLS هي الطبقةُ الوحيدة** هنا لا الثانية —
-- وهذا مسجَّلٌ بـADR-054 منذ ٠٥٣ب.
-- ==========================================================================

select 'سياسة' as kind, p.policyname as name, p.cmd as detail,
       coalesce(p.qual, '—') as using_clause,
       coalesce(p.with_check, '—') as check_clause
from pg_policies p
where p.schemaname = 'public' and p.tablename = 'stock_lots'

union all

select 'منحة', g.grantee, g.privilege_type, '—', '—'
from information_schema.role_table_grants g
where g.table_schema = 'public' and g.table_name = 'stock_lots'

order by kind, name, detail;

-- ==========================================================================
-- ⚠️ أُضيف بعد التشغيل. **وجملةُ `select` أعلاه لم تتغيّر** — هي بالحرف ما نُفِّذ.
--
-- 🔴 ترويسةُ هذا الملفِّ تناقض نفسَها، والمالكُ سأل عنها
--
-- تقول في موضعٍ الصوابَ — «وجودُ `anon` متوقَّعٌ ولا يُقرأ ثغرة… وRLS هي الطبقةُ
-- الوحيدة هنا لا الثانية، مسجَّلٌ بـADR-054» — **وتقول قبله عكسَه**: «المنعُ
-- مقصودٌ من طبقتين: السياسةُ تُصفّي الصفوف، والمنحةُ تقرّر إن كان الدورُ يلمس
-- الجدولَ من الأساس»، ثمّ تكتب في المتوقَّع «`SELECT` و`INSERT` لـ`authenticated`
-- — ولا `UPDATE`/`DELETE`».
--
-- **والمقيسُ عند التشغيل: السبعُ صلاحيّاتٍ لـ`anon` و`authenticated` معًا.**
--
-- ⚠️ **فالخطأُ ليس في نصفٍ من الترويسة بل في وجود النصفين معًا:** قارئٌ يصدّق
-- أيَّهما شاء، **ومتوقَّعٌ مكتوبٌ خطأً يجعل المخرَجَ الصحيحَ يُقرأ عطلًا** — وهو
-- ما وقع فعلًا حتى قرأه المالك.
--
-- ---------------------------------------------------------------------------
-- 🔴 والمتوقَّعُ **تغيّر** بعد ٠٩٤ج — فأعِد تشغيلَ هذا الملفِّ بعده
--
-- ٠٩٤ج يسحب `UPDATE`/`DELETE`/`TRUNCATE`/`TRIGGER`/`REFERENCES` من `anon` و
-- `authenticated` على `stock_lots` و`stock_movements` و`stock_documents`.
--
--   السياسات:  `select` و`insert` فقط — **بلا تغيير**
--   المِنَح:    `SELECT` و`INSERT` فقط للاثنين — **بعد ٠٩٤ج، لا قبله**
--
-- ⇒ **وعندها تصير جملةُ «طبقتان» صحيحةً لأوّل مرّة** — على هذه الثلاثة وحدَها،
-- وبقرارٍ مكتوبٍ في ٠٩٤ج يقول لماذا هي بالذات دون الـ٤١.
--
-- ⚠️ **وقبل ٠٩٤ج تبقى الطبقةُ واحدة، وهي كافية:** RLS ترفض أيَّ أمرٍ لا سياسةَ
-- له، فغيابُ سياستَي التعديل والحذف حظرٌ بنيويّ. **الذي سقط ادّعاءُ العدد، لا
-- الحماية.**
-- ==========================================================================
