-- ١٠٠ — تشخيصٌ لا تغيير: **كم سندَ توريدٍ حقيقيٍّ لكلّ مورّدٍ في كلّ مستودع؟**
--
-- 🔴 قراءةٌ فقط. ولا `insert` ولا `update` ولا DDL — **يُشغَّل ويُعاد تشغيلُه
-- بلا أثر.**
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر وRLS متجاوَزة** — فهذا يعرض **كلَّ
-- الصالونات**، لا صالونَ المستخدم. والعمودُ `salon_id` معروضٌ لهذا السبب:
-- **صفٌّ من صالونٍ آخرَ يبدو صفَّك تمامًا** ما لم يُقرأ.
--
-- ---------------------------------------------------------------------------
-- السؤالُ الذي يُجيبه، ولماذا هو السؤالُ الصحيح
--
-- «إدخال من فاتورة» في شاشة الإرجاع صار مقصورًا على:
--
--     doc_type = 'supply'          ← الطلبيّةُ لا تولّد دفعةً إطلاقًا
--     storage_id = مستودعُ العدسة   ← دفعةٌ في مستودعٍ آخرَ لا تُرجَع من هنا
--     supplier_id = المورّدُ المختار ← بضاعةُ مورّدٍ آخرَ ليست له
--
-- **فإن كان المورّدُ المجرَّبُ بلا سندِ توريدٍ يطابق الثلاثة، فالنافذةُ فارغةٌ
-- بحقّ** ولا عطلَ في الملء.
--
-- ⚠️ **لكنّ بلاغَ المالك يقول «يختار الفاتورة»** — أي أن المنتقيَ عرض صفًّا.
-- **فهذا السكربتُ يستبعد الفرعَ الآخرَ بالقياس، ولا يُتوقَّع أن يُظهر صفرًا.**
--
-- ---------------------------------------------------------------------------
-- 🔴 والعمودُ الحاسمُ `lots` لا `docs`
--
-- سندُ توريدٍ **بلا دفعاتٍ** يظهر في المنتقي (فهو مستندُ توريد) **ولا يملأ
-- شيئًا** — و`fillFromSupplyInvoices` تدور على الدفعات لا على المستندات.
-- **فمستندٌ قديمٌ سابقٌ لـ٠٩٤ لا `lot_id` له يعطي بالضبط: صفٌّ يُختار ولا كمّيّةَ
-- تتحدّث.**
--
-- ⚠️ **و`live_lots` أضيقُ منها:** دفعةٌ استُهلكت بالكامل تُتخطّى بـ`empty`،
-- فتملأ صفرًا — أي **صفٌّ يُختار ولا شيءَ يظهر كذلك.** والعمودان يفترقان هنا.
-- ==========================================================================

select
  s.salon_id,
  coalesce(sup.name, '(بلا مورّد)')            as supplier,
  d.supplier_id,
  st.name                                      as storage,
  d.storage_id,
  count(distinct d.id)                         as docs,
  -- ⚠️ **كم دفعةً ولّدها هذا التوريدُ فعلًا** — وهو ما يقرؤه الملء.
  count(distinct l.id)                         as lots,
  -- **ومنها ما زال فيه رصيد.** دفعةٌ مستنفَدةٌ تُتخطّى ولا تملأ.
  count(distinct l.id) filter (where rem.remaining > 0) as live_lots,
  min(d.doc_date)::date                        as first_doc,
  max(d.doc_date)::date                        as last_doc
from public.stock_documents d
cross join lateral (select d.salon_id) s(salon_id)
left join public.suppliers sup
       on sup.id = d.supplier_id and sup.salon_id = d.salon_id
left join public.storages st
       on st.id = d.storage_id and st.salon_id = d.salon_id
left join public.stock_lots l
       on l.source_document_id = d.id and l.salon_id = d.salon_id
left join lateral (
  -- 🔴 **المتبقّي مجموعُ حركاتٍ لا عمودٌ يُقرأ** (ADR-051) — ولا عمودَ
  -- `quantity_remaining` بهذا المخطّط أصلًا.
  select coalesce(sum(m.quantity_base), 0) as remaining
    from public.stock_movements m
   where m.lot_id = l.id
) rem on true
where d.doc_type = 'supply'
group by s.salon_id, sup.name, d.supplier_id, st.name, d.storage_id
order by s.salon_id, storage, supplier;

-- ---------------------------------------------------------------------------
-- كيف يُقرأ المخرَج — والحالاتُ الثلاثُ تبدو متشابهةً على الشاشة
--
--   docs = 0                      ⟵ المنتقي **فارغ**. لا عطلَ ملء.
--   docs > 0 و lots = 0           ⟵ صفٌّ يُختار **ولا كمّيّةَ تتحدّث**.
--                                    مستندٌ سابقٌ لمحرّك الدفعات (٠٩٤).
--   docs > 0 و lots > 0 و live = 0 ⟵ صفٌّ يُختار **ولا كمّيّةَ تتحدّث**.
--                                    الدفعاتُ مستنفَدةٌ كلُّها.
--   docs > 0 و live_lots > 0      ⟵ **يجب أن يملأ.** فإن لم يملأ فالعطلُ
--                                    في الشاشة لا في البيانات.
--
-- ⚠️ **وحالةٌ رابعةٌ لا يراها هذا السكربتُ إطلاقًا، ومقيسةٌ بالكود:** مربّعُ
-- «منتجات الأمانة» مؤشَّرٌ ومنتجاتُ الفاتورة ليست أمانةً لهذا المورّد —
-- **فالملءُ ينجح والصفوفُ تُرشَّح بعده فلا تظهر.** لا أثرَ لها في القاعدة،
-- **والشاشةُ صارت تقولها بشريطٍ صريحٍ بعد إصلاح اليوم.**
