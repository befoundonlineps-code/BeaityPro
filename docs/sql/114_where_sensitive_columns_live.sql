-- 114 -- أين تُخزَّن الحقولُ الحسّاسة، وبأيّ نوع؟
--
-- ==========================================================================
-- 🔴 قراءةٌ محضة، وعلى **الوصف لا على المحتوى**: يقرأ أسماءَ الأعمدة
--    وأنواعَها، **ولا يقرأ قيمةً واحدةً**. لا `create` ولا `alter` ولا
--    `drop` ولا `insert` ولا `update` ولا `delete` — ولا كتلةَ `do`.
--    جملةُ `select` واحدةٌ لا غير.
--
-- 🔴 وهذا مقصودٌ لا عرَض: القاعدةُ فيها بياناتُ زبائنَ فعليّين، ومخرَجُ
--    هذا الملفّ يُنسَخ في محادثة. **فلا يخرج منه رقمُ جوازٍ واحد.**
-- ==========================================================================
--
-- ── ما يجيب عنه ───────────────────────────────────────────────────────────
--
-- اسمُ الجدول · العمود · النوع · أيقبل العدم · أله قيمةٌ ضمنيّة — لكلّ عمودٍ
-- **يطابق اسمُه إبرةَ حساسيّة**. ومعه صفٌّ يقول أمثبَّتةٌ `pgcrypto`.
--
-- ── 🔴 حدُّه الأوّل، وهو أثقلُ من كلّ ما بعده ──────────────────────────────
--
-- **هذا فرزٌ بالاسم، لا فحصٌ للمحتوى.** فعمودٌ اسمُه `note` يحمل أرقامَ
-- جوازاتٍ **لا يظهر هنا إطلاقًا**، وعمودٌ اسمُه `passport_photo_url` يظهر
-- وهو رابطٌ لا رقم. ⇒ **فالمخرَجُ قائمةُ مرشَّحين، لا حصرًا للحقول
-- الحسّاسة، ولا يُقرأ «هذه كلُّها».**
-- ⚠️ **والإبرُ مكتوبةٌ بيدٍ أدناه** ⟹ **تفشل مفتوحة**، وكلُّ لفظٍ خارجها
-- يسقط صامتًا. **ويُقرأ الفرقُ: صفرُ نتائجَ يعني «لم تطابق إبرةٌ»، لا
-- «لا حقولَ حسّاسة».**
--
-- ── ⚠️ وحدودٌ أخرى ─────────────────────────────────────────────────────────
--
-- ② **مخطَّطُ `public` وحدَه** — و`auth.users` خارجَه، وفيه بريدٌ وهاتفٌ
--    ومعرِّفاتٌ يديرها Supabase. **مدًى لم يُقَس، لا مدًى فارغ.**
--
-- ③ **و«أثمّة تشفيرٌ في العمود نفسِه» لا يُقاس بالنوع وحدَه.** النوعُ
--    `bytea` قد يكون صورةً، و`text` قد يحمل نصًّا مشفَّرًا بمفتاحٍ في
--    التطبيق. ⇒ **فيُطبع النوعُ شاهدًا، ويُطبع وجودُ `pgcrypto` بجانبه،
--    ولا يُستنتج من أحدهما تشفير.**
--
-- ④ **ولا يُقاس من يقرأ هذه الأعمدة.** ذاك ملفُّ ١١٢ (الصلاحيّاتُ وRLS)،
--    ويُقرآن معًا: عمودٌ حسّاسٌ في جدولٍ بلا RLS ليس كعمودٍ في جدولٍ بها.
--
-- ── 📌 التوقُّعُ، مُعلَنٌ قبل التشغيل ───────────────────────────────────────
--
-- **لا أُعلن عددًا ولا أسماء: لم أقرأ مخطَّطَ الإنتاج، ولم أجد في
-- `docs/sql` نصًّا يُنشئ عمودَ جوازٍ أو رقمٍ تعريفيّ.** ⇒ **فالتوقُّعُ هنا
-- «لا أعرف»، ويُقال كذلك — وأيُّ عددٍ أكتبه سيكون من الظنّ لا من النصّ (③ب).**
-- 🔴 **وأصدقُ ما يُعلَن قبل هذا التشغيل: أنّ صفرًا وغيرَ صفرٍ كلاهما خبر.**
--
-- ==========================================================================

with needles(pat) as (
  values ('passport'), ('national'), ('nid'), ('ssn'), ('iqama'), ('identity'),
         ('id_number'), ('idnumber'), ('civil_id'), ('civilid'),
         ('tax'), ('vat_number'), ('birth'), ('dob'),
         ('iban'), ('card'), ('account_number'), ('bank'),
         ('جواز'), ('هوية'), ('هويّة'), ('وطني'), ('وطنيّ')
)
select
  c.table_name                        as "الجدول",
  c.column_name                       as "العمود",
  c.data_type                         as "النوع",
  c.is_nullable                       as "يقبل العدم",
  coalesce(c.column_default, '—')     as "القيمةُ الضمنيّة",
  (select string_agg(n.pat, ', ') from needles n
    where c.column_name ilike '%' || n.pat || '%')
                                      as "الإبرةُ التي طابقت"
from information_schema.columns c
join pg_class     k on k.relname = c.table_name
join pg_namespace s on s.oid = k.relnamespace and s.nspname = 'public'
where c.table_schema = 'public'
  and k.relkind in ('r', 'p')
  and exists (select 1 from needles n where c.column_name ilike '%' || n.pat || '%')

union all

select
  '‹صفُّ سياقٍ لا جدول›',
  'pgcrypto مثبَّتة؟',
  case when exists (select 1 from pg_extension where extname = 'pgcrypto')
       then 'نعم' else 'لا' end,
  '—',
  '—',
  'لا تُقرأ إثباتًا للتشفير — تُقرأ شرطًا لإمكانه'

order by 1, 2;
