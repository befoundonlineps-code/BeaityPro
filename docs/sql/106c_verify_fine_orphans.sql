-- 106c -- VERIFICATION ONLY. One SELECT, and it changes nothing.
--
-- 🔴 لماذا هو ملفٌّ مستقلٌّ ولم يبقَ عمودًا في ١٠٦ب — والسببُ مقيسٌ لا مُفترَض
--
-- **كان عمودًا اسمُه `orphan_fines` داخل ١٠٦ب. ونفّذ المراجعُ ١٠٦ب على قاعدةٍ
-- لا يوجد فيها `stock_document_liveness`** — أي **الحالةَ التي بُني العمودُ
-- `liveness_exists` لكشفها بعينها:
--
--   ERROR:  42P01: relation "public.stock_document_liveness" does not exist
--   LINE 39:       select 1 from public.stock_document_liveness l
--
-- ⇒ **صفرُ مخرَج. ولا صفَّ نتيجةٍ إطلاقًا.** و`liveness_exists = 0` — الشاهدُ
-- الذي يقول «هذا هو السبب» — **لا يُطبع أبدًا**، لأن الجملة كلَّها تسقط قبل
-- التنفيذ. **وبنفس الرمز `42P01` الذي تقول ترويسةُ ١٠٦ب إنها تتجنّبه عمدًا
-- بترك `::regclass`** — فأعاده عمودٌ واحدٌ من الباب الخلفيّ.
--
-- **والسببُ بنيويٌّ لا موضعيّ:** بقيّةُ أعمدة ١٠٦ب تقرأ **الكتالوج**
-- (`pg_class` · `pg_attribute` · `pg_constraint`) فتُجيب `0` أو عدمًا حين يغيب
-- الكائن. **وهذا يقرأ الجدولين فعلًا** — وpostgres يحلّ أسماءَ العلاقات **وقتَ
-- التحليل لا وقتَ التنفيذ**. ⇒ **فلا موضعٌ في القائمة ينجو، ولا
-- `case … when exists` يحمي، ولا ترتيبُ الأعمدة يغيّر شيئًا.**
--
-- ✅ **والإصلاحُ مقيسٌ لا مُخمَّن:** حُذف العمودُ وحدَه وأُعيد التشغيلُ على نفس
-- القاعدة الناقصة، **فظهر التشخيصُ كاملًا** (`view_exists 0` ·
-- `liveness_exists 0` · القيودُ والأعمدةُ مسرودة).
--
-- ⚠️ **والخطأُ خطأُ المراجع بلفظه** — العمودُ اقتراحُه، وكُتب بلا فحصِ أثرِه على
-- خاصّيّةِ هذا الملفّ، **ونُفّذ هنا حرفًا كما طُلب.** ويُنسب إليه في النصّ.
--
-- ---------------------------------------------------------------------------
-- والفصلُ بالنوع، لا حلًّا وسطًا — وهو منطقُ ٠٧٩أ/٠٧٩ب_٢ نفسُه
--
--   106b  فحصُ **شكلٍ وصلاحيّةٍ ونصّ** ⟵ كتالوجٌ خالص، ينحدر لطيفًا دائمًا
--   106c  فحصُ **بيانات**            ⟵ يقرأ الجدولين، فيسقط إن غاب أحدُهما
--
-- ⇒ **وسقوطُه المستقلُّ خبرٌ لا كارثة:** يرفع `42P01` وحدَه، **وقد قُرئ
-- `liveness_exists` من ١٠٦ب قبله.**
--
-- ---------------------------------------------------------------------------
-- ⚠️ وماذا يمسك هذا العدُّ فعلًا — وهو أوسعُ من حجّته
--
-- الحجّةُ في ١٠٦ تقول إن العدمَ مستحيلٌ بشرطين: الـview إسقاطٌ كامل، والمفتاحُ
-- مركّب. **وقاس المراجعُ شرطًا ثالثًا ناقصًا منها:** `f.document_id` عدمًا يجعل
-- `l.document_id = f.document_id` **غيرَ محقَّقٍ أبدًا**، فيعود `is_void` عدمًا.
-- ⇒ **فـ`not null` على العمود شرطٌ حاملٌ ثالث.**
--
-- ✅ **وهذا العدُّ يمسكها:** `not exists` مع مقارنةٍ عدميّةٍ **يَعُدّ الصفّ**.
-- مقيسًا عند المراجع: `orphan_fines = 1` و`null_is_void = 1` على صفٍّ
-- `document_id` فيه عدم. **فالحارسُ أوسعُ من الحجّة التي بُني عليها.**
--
-- ⚠️ **وقيمتُه اليوم مستقبليّةٌ بالكامل:** `stock_fines` فارغٌ (صفّره ٠٨٩)،
-- **فالصفرُ هنا بحكم الجدول لا بحكم سلامة الشروط** — وهو عينُ «فحصٌ لا يقدر
-- أن يفشل ليس فحصًا» (البند ٨). **يصير حارسًا حقيقيًّا لحظةَ أوّل صفّ.**
--
-- ⚠️ **وترتيبُ التشغيل: ١٠٦ ثمّ ١٠٦ب ثمّ ١٠٦ج** — فإن قال ١٠٦ب
-- `liveness_exists = 0` **فلا يُشغَّل ١٠٦ج أصلًا**: جوابُه معروفٌ سلفًا، وهو خطأ.
-- ==========================================================================

select
  (select count(*) from public.stock_fines f
    where not exists (
      select 1 from public.stock_document_liveness l
       where l.document_id = f.document_id
         and l.salon_id    = f.salon_id
    ))                                                       as orphan_fines,

  -- ⚠️ **وعددُ اللاغيةِ عدمًا بجانبه** — لأن العدَّين معًا يفرّقان بين
  -- «الشرطُ الثالث ساقط» (عدمٌ في `document_id`) و«الأوّلان ساقطان»
  -- (صفٌّ يتيمٌ بمعرِّفٍ حقيقيّ). **ورقمٌ واحدٌ لا يميّزهما.**
  (select count(*) from public.stock_fine_voidness where is_void is null) as null_is_void;
