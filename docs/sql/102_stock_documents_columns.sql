-- ١٠٢ — أعمدةُ `stock_documents` كما هي بالكتالوج، وهل يحمل `doc_date` وقتًا.
--
-- **قراءةٌ فقط. ولا `DDL` ولا كتابةَ صفٍّ واحد** — فما فيه شيءٌ يمكن أن يتراجع،
-- والبند ١ لا يمسّه.
--
-- **وجملةُ `select` واحدة** — محرّرُ Supabase يعرض مجموعةَ النتائج الأخيرة
-- وحدَها، **ويبتلع ما قبلها بصمت.**
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر وRLS متجاوَزةٌ بالكامل هناك.** وهنا
-- **هذا في صالحنا لا ضدّنا**: العدُّ أدناه يرى كلَّ الصفوف لا صفوفَ صالونٍ
-- واحد. **لكنّه — كالعادة — لا يثبت شيئًا عن العزل.**
--
-- ══════════════════════════════════════════════════════════════════════
-- لماذا هذا السؤال أصلًا
-- ══════════════════════════════════════════════════════════════════════
--
-- مواصفةُ «قائمة الفواتير» تطلب **عمودَ وقت**. والمستودعُ لا يملك جوابًا:
--
--   • `DATABASE_DIAGRAM:572` يسرد أعمدةَ `stock_documents` **بلا `created_at`**
--     — لكنّ `:576` يقول صراحةً إن السرد مأخوذٌ من **نصوص الدوالّ**، أي
--     الأعمدةَ التي **تمسّها**، لا أعمدةَ الجدول. **فغيابُه هناك ليس غيابًا.**
--
--   • `lib/stockDocumentList.js:237` يقرأ `document.created_at` فاصلًا للتعادل
--     في الترتيب — **فالكودُ يفترضه موجودًا منذ جولات.**
--
-- ⇒ **وهذا بالضبط «لم يُقَس ≠ غير موجود».** والسؤالُ يُسأل للكتالوج.
--
-- ══════════════════════════════════════════════════════════════════════
-- ولماذا **كلُّ** الأعمدة، لا `where column_name = 'created_at'`
-- ══════════════════════════════════════════════════════════════════════
--
-- ⚠️ **سؤالٌ ضيّقٌ للكتالوج يفشل مفتوحًا كقائمةٍ مكتوبةٍ بيد** — `contype = 'c'`
-- كان سؤالًا للكتالوج ولم يرَ النوع. **فتُقرأ الفئةُ كاملةً وتُصفَّى بالعين.**
--
-- وقد يكون الاسمُ `inserted_at` أو `recorded_at` أو `posted_at`؛ **والبحثُ
-- بالاسم يفشل مفتوحًا** (`reversed_document_id` ⟵ `reverses_document_id`).
--
-- ⚠️ **والإسقاطُ الضيّق يُخفي بلا أثرٍ إطلاقًا** — `079b_1` أسقط `domain_name`
-- **وهي معبّأة**، فقُرئ `text · YES` «مجالٌ مفتوح» عن عمودٍ مقيَّد. فهي هنا.
--
-- ══════════════════════════════════════════════════════════════════════
-- شاهدُ الصدق — النتيجةُ الفارغةُ لها معنيان، وهذا يفصلهما
-- ══════════════════════════════════════════════════════════════════════
--
-- **يجب أن تظهر هذه الأربعةُ في المخرَج، ونحن نعرفها موجودة:**
--
--     doc_date  ·  paid_amount  ·  reverses_document_id  ·  doc_number
--
-- ✅ ظهرت ⟵ الاستعلامُ يرى الجدول، **فغيابُ `created_at` خبرٌ لا صمت.**
-- ❌ لم تظهر ⟵ الاستعلامُ لم يصل الجدولَ أصلًا، **ولا يُقرأ منه أيُّ نفي.**
--
-- ══════════════════════════════════════════════════════════════════════
-- والعمودان الأخيران يجيبان سؤالًا ثانيًا بلا استعلامٍ ثانٍ
-- ══════════════════════════════════════════════════════════════════════
--
-- **هل يحمل `doc_date` وقتًا حقيقيًّا؟** المستودعُ يقول لا: الشاشاتُ الأربعُ
-- كلُّها `<Input type="date">`، **فالقيمةُ تصل `2026-08-04T00:00:00+00:00`**
-- (مقروءةٌ من صفوفٍ حقيقيّةٍ ومكتوبةٌ في `stockDocumentList.js:281`).
--
-- ⇒ **وعمودُ وقتٍ مصدرُه `doc_date` سيطبع «١٢:٠٠ ص» على كلّ صفٍّ إلى الأبد.**
--
-- **و`docs_not_midnight = 0` يقول: كلُّ صفٍّ موجودٍ اليوم منتصفَ ليل.**
-- ⚠️ **وهي جملةٌ عن شكل ما يكتبه كودُنا، لا عن تواتُرٍ** — صفوفُ هذه القاعدة
-- اختباريّة، **فهي تجيب أسئلةً بنيويّةً ولا تجيب سؤالَ تواتُرٍ أبدًا.**
--
-- ⚠️ **و`to_char` لا `::time` عمدًا:** `date::time` يرفضه بوستجرس، **فلو كان
-- العمودُ `date` لسقط الاستعلامُ كلُّه ولم يصل شيء.** و`to_char` يعمل مع
-- الاثنين.

select
  c.ordinal_position,
  c.column_name,
  c.data_type,
  c.udt_name,
  c.domain_name,
  c.is_nullable,
  c.column_default,
  c.numeric_precision,
  c.numeric_scale,
  c.datetime_precision,
  (select count(*) from public.stock_documents) as docs_total,
  (select count(*) from public.stock_documents
    where to_char(doc_date, 'HH24:MI:SS') <> '00:00:00') as docs_not_midnight
from information_schema.columns c
where c.table_schema = 'public'
  and c.table_name = 'stock_documents'
order by c.ordinal_position;
