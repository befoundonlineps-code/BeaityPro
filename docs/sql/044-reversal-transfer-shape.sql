-- البند ٥٥ — عكسُ التحويل مرفوضٌ بقيدٍ كُتب قبل أن يوجد شكلُ العكس
--
-- ⚠️ مُجهَّز ومعروض ولا يُشغَّل من طرفي — المالك ينفّذه بمحرّر SQL.
--
-- ⚠️ **مستقلٌّ تمامًا عن ٠٤٣ (التكلفة المقدَّرة)، ويسبقه.** عيبٌ إنتاجيّ قائم
--    يمنع فعلًا يحتاجه المالك اليوم، ولا علاقة له بالعمود الجديد — فلا سبب
--    لتأخيره خلفه، ولا لخلطه به.
--
-- ⚠️ ولا `RAISE EXCEPTION` يُنفِّذه هذا السكربت، ولا `do`، ولا جدول مؤقّت.
--    جملتا `alter` وثلاث `select`، والتحقّق كله بالآخر.
--
-- ✅ ويُشغَّل كاملًا. **وأخفق بالمنتصف؟ شغّله مرّةً أخرى** — لا شيء فيه ذو
--    اتّجاهٍ واحد: لو نجح `drop` وأخفق `add` ارتدّت المعاملة كاملةً وبقي
--    القيد القديم حيًّا (الـDDL معاملة كأي شيء آخر).
-- ═══════════════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────────────
-- التشخيص — مقروءٌ من نصَّي الدالّتين، لا مستنتَجًا من الرسالة
-- ───────────────────────────────────────────────────────────────────────────
--
-- القيد القائم:
--
--   CHECK ((doc_type = 'transfer'::stock_doc_type) = (to_storage_id IS NOT NULL))
--
-- يربط وجودَ `to_storage_id` بنوع `transfer` **حصرًا وبالاتّجاهين**.
--
-- و`reverse_stock_document` تُدرج ترويسةً **تنسخ `to_storage_id` من أصلها
-- حرفًا، ويصير نوعها `'reversal'` دائمًا**:
--
--   values (v_src.salon_id, 'reversal', v_src.storage_id, v_src.to_storage_id, …)
--             ↑ النوع ثابت                                  ↑ والعمود منسوخ
--
-- فينقسم السلوك قسمين، **وكلاهما حتميّ لا عارض**:
--
--   عكسُ توريد   `post_stock_document` لا تُدرج `to_storage_id` إطلاقًا (ليس
--                بقائمة أعمدتها) ⇒ `NULL` بالأصل، و`NULL` بالعكس
--                ⇒ (false) = (false) ⇒ **يمرّ**
--
--   عكسُ تحويل   `transfer_stock` تُدرجه بقيمةٍ حقيقية ⇒ العكس يحمله
--                ونوعه `'reversal'`
--                ⇒ (false) = (true)  ⇒ **يُرفض بـ23514**
--
-- ⚠️ **فكلّ عكسٍ لغير التحويل كان سينجح دائمًا، وعكسُ التحويل كان سيفشل
--    دائمًا** — والتحويل وحده يملك عمودًا ثانيًا يُنسخ معه. وبيانات المالك
--    قالت هذا قبل أن يُقرأ القيد: عكسان لتوريدين نجحا، وعكسٌ لتحويل فشل.
--
-- ✅ **ولماذا لم يمسكه حارسُ تطبيق:** كل قيدٍ آخر على هذين الجدولين يسبقه
--    `raise` بالدوالّ — `transfer_same_storage` قبل قيد اختلاف المستودعين،
--    و`stock_line_zero` قبل قيد الكمّية، و`unit_cost_required` قبل قيد
--    السالب. **وهذا وحده بلا حارس، لأنه كُتب حين لم يكن شكلُ «عكسِ تحويل»
--    موجودًا بعد** — فلا حارسَ توقّعه.
-- ───────────────────────────────────────────────────────────────────────────


-- ───────────────────────────────────────────────────────────────────────────
-- ⚠️ يُقرأ قبل التعديل — التعريف الحاليّ بالاسم والنصّ
--
-- **لا يُشغَّل `drop` على اسمٍ مفترَض.** لو اختلف الاسم فشل الحذف (وهذا فشلٌ
-- مغلق، جيّد) — لكن الأنفع أن يُقرأ النصّ فيُرى أنه هو المقصود فعلًا، لا
-- قيدٌ آخر صادف الاسم.
-- ───────────────────────────────────────────────────────────────────────────

select conname, pg_get_constraintdef(oid) as definition
from pg_constraint
where conrelid = 'public.stock_documents'::regclass and contype = 'c'
order by conname;


-- ───────────────────────────────────────────────────────────────────────────
-- التعديل — إرخاءٌ لا تشديد
--
-- ✅ **والقيد الجديد أوسع من القديم بالتحديد**: أُضيف شقٌّ بـ`or`، فكل صفٍّ
--    كان يمرّ القديم يمرّ الجديد. **فلا خطر على أيّ صفّ قائم، ولا حاجة
--    لـ`not valid` ولا لفحص بياناتٍ سابقة** — والفحص عند الإضافة يمسح
--    الجدول ويقبل الجميع.
--
-- ✅ **والمستثنى `'reversal'` وحده**، لا كل الأنواع ولا `to_storage_id` بلا
--    شرط. التوريد والشطب والإرجاع والجرد والتهيئة والبيع والصرف تبقى محكومةً
--    بالقيد الأصليّ كما كانت حرفًا بحرف.
--
-- ⚠️⚠️ **والثمن يُقال صراحةً، لا يُبتلع:** بعد هذا، **لا شيء بمستوى الجدول
--    يضمن أن صفّ `reversal` يحمل `to_storage_id` الصحيح.** الضمان كلّه أن
--    `reverse_stock_document` هي **المسار الوحيد** الذي يكتب `reversal`،
--    وأنها تنسخه من أصله بأمانة.
--
--    **وهذا أخو `SECURITY INVOKER` على `transfer_stock` بالضبط** (البند ٥٣
--    وجواره): حمايةٌ حقيقية تسكن بالدالّة لا بتوقيع الجدول. **ويوم يُضاف
--    مسارٌ ثانٍ يكتب `reversal` مباشرةً — لأي سببٍ يبدو وجيهًا — يفلت بلا أن
--    يشتكي شيء.**
--
--    والبديل الأحكم موجود ومرفوضٌ عن قصد: `constraint trigger` يقرأ نوع
--    الأصل عبر `reverses_document_id` ويقارن. فحصٌ يُشغَّل بكل `insert` مقابل
--    نظافةٍ نظريةٍ لخطرٍ له اليوم مسارٌ واحد ثابت — **وهو ميزان ADR-051 نفسه:
--    ختمٌ بسيطٌ يُتَّكَل عليه، لا تعقيدٌ لحالةٍ لم تقع.**
-- ───────────────────────────────────────────────────────────────────────────

alter table stock_documents
  drop constraint stock_documents_transfer_shape_check;

alter table stock_documents
  add constraint stock_documents_transfer_shape_check
  check (
    doc_type = 'reversal'::stock_doc_type
    or (doc_type = 'transfer'::stock_doc_type) = (to_storage_id is not null)
  );


-- ───────────────────────────────────────────────────────────────────────────
-- التحقّق
-- ───────────────────────────────────────────────────────────────────────────

-- ١. ⚠️ **النصّ يُقرأ، لا وجود الاسم.** الاسم نفسه بقي، فسردٌ يقول «القيد
--    موجود» يقول الشيء نفسه قبل التعديل وبعده — وهو عين درس `security_invoker`
--    و`indisunique`: سردُ الشكل ليس قراءةَ المعنى.
--    **المتوقَّع أن يظهر `'reversal'` بالنصّ الراجع.**
select conname, pg_get_constraintdef(oid) as definition
from pg_constraint
where conrelid = 'public.stock_documents'::regclass
  and conname = 'stock_documents_transfer_shape_check';

-- ٢. وواحدٌ فقط بهذا الاسم — لا نسختان بعد drop/add ناقص.
--    **المتوقَّع: ١.**
select count(*) as copies
from pg_constraint
where conrelid = 'public.stock_documents'::regclass
  and conname = 'stock_documents_transfer_shape_check';

-- ٣. وكل صفٍّ قائم يجتاز القيد الجديد — يُقرأ لا يُفترَض.
--    **المتوقَّع: صفر صفوف.** (وإن رجع صفّ فالإضافة كانت سترفض أصلًا، فهذا
--    فحصٌ على الفهم لا على النتيجة.)
select id, doc_type, storage_id, to_storage_id
from stock_documents
where not (
  doc_type = 'reversal'::stock_doc_type
  or (doc_type = 'transfer'::stock_doc_type) = (to_storage_id is not null)
);


