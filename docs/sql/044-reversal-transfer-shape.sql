-- ⚠️ وما يصير مرئيًّا بعد هذا التعديل — يُقرأ قبل إعادة المحاولة
--
-- عكسُ التحويل كان مستحيلًا، **فما رآه أحدٌ قطّ كيف يُرسَم.** وترويسة العكس
-- تنسخ `storage_id` و`to_storage_id` كما هما، **بينما حركاته تسير بالاتّجاه
-- المعاكس** (`-m.quantity_base` عند `m.storage_id` نفسه):
--
--   التحويل الأصليّ   −75 @ العام    +75 @ التجربة   ⇒ عام ← تجربة
--   عكسُه             +75 @ العام    −75 @ التجربة   ⇒ تجربة ← عام
--   وترويسته تقول     من: العام · إلى: التجربة       ⇐ اتّجاه الأصل
--
-- و[components/StockDocumentsList.js](../../components/StockDocumentsList.js)
-- يرسم الشارتين من الترويسة (`fromStorage`/`toStorage`) والسطور من الحركات —
-- **فالبطاقة الواحدة ستقول شيئين متناقضين عن نفسها.** لا التباسًا: تناقضًا
-- ظاهرًا لمن يفتح المستند.
--
-- ولا يُعالَج بهذا السكربت (بندٌ مستقلّ)، والخياران:
--   ① الشاشة تصف الترويسة بما هي: «عكسُ تحويل من … إلى …» — أي أنها سياقٌ
--      موروثٌ عن الأصل لا اتّجاهُ هذا المستند. **بلا SQL، وبلا تغيير معنى عمود.**
--   ② الدالّة تبدّلهما حين يكون الأصل تحويلًا. صادقةٌ بذاتها، **لكنها تغيّر
--      معنى `storage_id` على صفّ العكس** وتلزم تعديل دالّةٍ رابعة.
--
-- **والراجح ①** — العطل بالوصف لا بالبيانات، والترويسة تصف ما يُلغى بحقّ.
-- ───────────────────────────────────────────────────────────────────────────
