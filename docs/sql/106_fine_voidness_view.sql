-- ⚠️ `with (security_invoker = true)` مكتوبةٌ صراحةً — البند ٦: أيّ
-- `create or replace view` يعيد كتابة الكائن كاملًا، **وكلُّ خاصّيّةٍ لا تُذكر
-- معرَّضة.** وضياعُها هنا يعني أن الـview يعمل بصلاحيّة مالكه، **فيرى كلُّ
-- صالونٍ غراماتِ كلّ صالون** — والفشلُ صامتٌ تمامًا ما دام في القاعدة صالونٌ
-- واحد.
create or replace view public.stock_fine_voidness
  with (security_invoker = true)
as
select
  f.id           as fine_id,
  f.salon_id,
  f.document_id,
  f.storage_id,
  f.employee_id,
  f.attribution,
  f.resolution,
  f.role_at_resolution,
  f.fine_percent,
  f.fine_basis,
  f.created_at,

  -- الجوابُ نفسُه، منفيًّا عن حيويّة المستند لا محسوبًا من جديد.
  not (select l.is_live
         from public.stock_document_liveness l
        where l.document_id = f.document_id
          and l.salon_id    = f.salon_id) as is_void,

  -- ومَن ألغاها — فالشاشةُ تستطيع أن تقول «أُلغيت بالمستند كذا» لا «لاغية» فقط.
  (select l.reversed_by_document_id
     from public.stock_document_liveness l
    where l.document_id = f.document_id
      and l.salon_id    = f.salon_id) as voided_by_document_id

from public.stock_fines f;

