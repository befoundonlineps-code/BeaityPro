-- ═══════════════════════════════════════════════════════════════════════════
-- مسبار: ماذا يفعل `select … into` حين لا يرجع صفًّا؟
--
-- ⚠️ **يُشغَّل قبل [043-cost-estimated.sql](043-cost-estimated.sql)، ونتيجته
--    تحكم عليه.** وهو نفسه ما وصل المالك بـ«سكربت ١٤».
--
-- ⚠️ قراءةٌ محضة: لا DDL دائم، ولا كتابة، ولا استثناء. جدولٌ مؤقّت وحده،
--    يزول بانتهاء الجلسة.
-- ═══════════════════════════════════════════════════════════════════════════
--
-- **لماذا يقف وحده ولماذا يسبق:**
--
-- ① **لا يحتاج شيئًا من ذاك السكربت** — لا العمود ولا الـview ولا الدوالّ.
--    يقرأ `stock_movements` كما هي اليوم. **ويملك حقّ نقضها جميعًا.**
--    وفحصٌ يملك النقض لا يقع بعد التنفيذ: حين يُقرأ تكون الأربع قد أُودعت،
--    و«أوقف كل شيء» تصير جملةً غير قابلة للتنفيذ.
--
-- ② **`do $$` هو الجملة الوحيدة القادرة على إسقاط المعاملة لسببٍ لا علاقة له
--    بالتغيير.** ولو أخفق وهو آخر شيء بسكربتٍ فيه DDL دائم، **ارتدّ معه كل ما
--    فوقه وقد بدا ناجحًا** — فالجملة الوحيدة القادرة على إلغاء التغيير كانت
--    الوحيدة التي لا تخصّه.
--
-- **وماذا يحكم:** سلسلة التكلفة **بالدوالّ الأربع** مبنيّة على أن
-- `select … into` يُسنِد العدم عند صفر صفوف — فـ`if v_cost is null` هو ما
-- ينقلها لدرجتها التالية. ولو كان يُبقي القيمة القديمة، فخيبةُ البحث تترك
-- **تكلفة المنتج السابق من الحلقة** مختومةً على هذا المنتج: **رقمٌ خاطئ،
-- مقنع، ودائم، ولا سطر يشتكي.**
--
-- التوثيق يقول «يُسنَد العدم» — **وثمانٍ من ملاحظاتنا عن هذه القاعدة قتلها
-- القياس**، فيُقاس مرّةً بدل أن يُفترض.
--
-- **المتوقَّع: `null-assigned ✓`. وأي شيء غيره يوقف ٠٤٣ كاملًا.**

create temporary table if not exists probe_select_into (result text);
delete from probe_select_into;   -- وإلا تراكمت سطور تشغيلٍ سابق بنفس الجلسة

do $$
declare v_probe numeric;
begin
  -- 999 لا `null`: لو ابتدأ عدمًا لكانت النتيجة عدمًا بالحالتين، **والفحص
  -- عاجزًا بنيويًّا عن التفريق** — وهو الصنف نفسه الذي نطارده.
  v_probe := 999;

  -- بشكل السلسلة نفسه حرفًا: نفس الجدول، نفس العمود، نفس الترتيب والحدّ.
  -- ومنتجٌ لا وجود له فالنتيجة صفر صفوف يقينًا.
  select unit_cost into v_probe
    from stock_movements
   where product_id = '00000000-0000-0000-0000-000000000000'::uuid
   order by created_at desc, id desc
   limit 1;

  insert into probe_select_into
  values (case when v_probe is null
               then 'null-assigned ✓ — السلسلة تنزل درجاتها كما هو مقصود'
               else 'stale: ' || v_probe || ' ⛔ — أوقف ٠٤٣ ولا تُشغّله' end);
end $$;

select * from probe_select_into;
