--
-- 🔴 مُجهَّزٌ ولم أشغّله. المالكُ ينفّذه بيده في محرّر Supabase.
-- ترتيبُ التشغيل: ٠٩٠ (هذا) ⟵ ٠٩٠ب (التحقّق، وفيه القراءةُ الراجعةُ للعربيّة).
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر، وRLS متجاوَزةٌ هناك بالكامل.** فنجاحُ
-- هذا السكربت يثبت أن العمودَ انضاف — **ولا يثبت شيئًا عن العزل بين
-- الصالونات.** العمودُ محكومٌ بسياسات `product_orders` القائمة (٠٥٣أ) ولا
-- يضيف سياسةً ولا يمسّ واحدة.
--
-- ---------------------------------------------------------------------------
-- لماذا: «رقم الفاتورة» في نافذة «طلب بضاعة»
--
-- التطبيقُ المرجعيُّ يعرض `Invoice №` في ترويسة النافذة، **ولا عمودَ يقابله
-- عندنا**: `product_orders` هي (id · salon_id · supplier_id · order_date ·
-- note · created_at) ولا شيءَ غيرها.
--
-- **وقرارُ المالك: يُعرض، واختياريّ.** فالحقلُ يُبنى بعموده بدل أن يُحشر في
-- `note` — وهو الفرقُ بين حقلٍ يمكن البحثُ فيه لاحقًا ونصٍّ حرٍّ لا يُقرأ آليًّا.
--
-- ⚠️ **ولا يُدّعى أنه رقمُ فاتورةِ التوريد.** الطلبيّةُ نيّةُ شراءٍ لا استلام،
-- ورقمُ الفاتورة الحقيقيُّ يصل مع البضاعة إلى مستند التوريد — والعمودُ هناك
-- موجودٌ منذ ٠٤٧ (`supplier_doc_number`). فهذا مرجعٌ يكتبه صاحبُ الطلب، ووصفُ
-- العمود أدناه يقول ذلك كي لا يُقرأ بعد سنةٍ على أنه الآخر.
--
-- ---------------------------------------------------------------------------
-- القيدُ، وهو القرارُ الوحيدُ هنا الذي ليس نسخًا
--
-- `invoice_no is null or length(btrim(invoice_no)) > 0`
--
-- ⚠️ **لأن الفراغَ يجب أن تكون له تهجئةٌ واحدة.** بلا هذا القيد يصل من الشاشة
-- إمّا `NULL` وإمّا `''` — وكلاهما «لم يُكتب رقم»، فيصير سؤالُ «هل لهذه الطلبيّة
-- رقمُ فاتورة؟» له جوابان يعتمدان على أيِّ نسخةٍ من الشاشة كتبت الصفّ. وهذا
-- المشروعُ يعرف هذا الصنفَ باسمه: **قيمتان لمعنًى واحدٍ هما جوابان يتباعدان.**
--
-- ⚠️ **والفرعُ `is null` مكتوبٌ صراحةً وليس تزيّدًا.** الـ`CHECK` لا يرفض إلّا
-- على FALSE، و`length(btrim(null)) > 0` تساوي UNKNOWN فتمرّ — أي أن القيدَ
-- **يعمل بدونه أيضًا** للعمود العديم. كُتب لأن قارئَه يجب أن يرى النيّةَ لا أن
-- يستنتجها، وهي القاعدةُ التي دفع ثمنَها ٠٥٢ب و٠٤٤.
--
-- ⚠️ **ولا `default`.** عمودٌ جديدٌ بـ`default` يكتب ادّعاءً عن كلّ صفٍّ قائم
-- (البند ٨)، والصحيحُ هنا أن الطلبيّاتِ السابقةَ **لم يُكتب لها رقم** — وهذا
-- بالضبط ما يقوله العدم.
-- ==========================================================================

alter table public.product_orders
  add column if not exists invoice_no text;

alter table public.product_orders
  drop constraint if exists product_orders_invoice_no_not_blank_check;

alter table public.product_orders
  add constraint product_orders_invoice_no_not_blank_check
  check (invoice_no is null or length(btrim(invoice_no)) > 0);

comment on column public.product_orders.invoice_no is
  'رقمٌ مرجعيٌّ يكتبه صاحبُ الطلب على الطلبيّة، اختياريٌّ دائمًا. ⚠️ ليس رقمَ فاتورة التوريد — ذاك يصل مع البضاعة ويُخزَّن في stock_documents.supplier_doc_number منذ سكربت ٠٤٧. الطلبيّةُ نيّةُ شراءٍ لا استلام، فلا شيءَ هنا يثبت أن فاتورةً وُجدت. والقيدُ يمنع الفراغَ النصّيَّ كي يبقى «بلا رقم» تهجئةً واحدةً هي العدم.';
