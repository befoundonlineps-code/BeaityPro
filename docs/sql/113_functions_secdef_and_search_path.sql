-- 113 -- كلُّ دالّةٍ في `public`: أهي `security definer`؟ وما `search_path`ها؟
--
-- ==========================================================================
-- 🔴 قراءةٌ محضة. لا `create` ولا `alter` ولا `drop` ولا `insert` ولا
--    `update` ولا `delete` ولا `grant` ولا `revoke` — ولا كتلةَ `do`.
--    جملةُ `select` واحدةٌ لا غير.
--
-- 🔴 والقاعدةُ إنتاجيّة. هذا الملفُّ **يقيس ولا يعالج**، ولا يصنّف خطرًا.
-- ==========================================================================
--
-- ── ما يجيب عنه — وهو بندان في سؤالٍ واحد ─────────────────────────────────
--
-- طُلب بندان منفصلان: «الدوالُّ `security definer`» و«الزارعان بلا
-- `search_path`». **وهما يُقاسان بصفٍّ واحدٍ لكلّ دالّة**، فجُمعا عمدًا:
-- المسحُ يُخرج كلَّ دوالّ `public` بعمودَي `prosecdef` و`proconfig`، فيقرأ
-- منه الأوّلُ صفوفَه والثاني صفوفَه. ⚠️ **ويُقال الجمعُ ولا يُسكَت عنه.**
--
-- ── 🔴 لماذا لا يُقرأ `search_path = public` تحصينًا ──────────────────────
--
-- **مقيسًا على PostgreSQL 18.3 (لا مرويًّا عن التوثيق):** دالّتان
-- `security definer` تقرآن اسمًا غيرَ مؤهَّل، ثمّ يُزرع جدولٌ مؤقّتٌ بالاسم
-- نفسِه:
--
--   search_path = public                     ⟶ قرأت **المزروع**
--   search_path = pg_catalog, public, pg_temp ⟶ قرأت **الدائم**
--
-- ⇒ **فـ`pg_temp` يُبحَث أوّلًا ما لم يُذكر صراحةً**، وذِكرُه أخيرًا هو ما
--    يزيحه. **فالعمودُ يُطبع بنصّه، ولا يُترجَم «محصَّن/غيرُ محصَّن» هنا** —
--    الترجمةُ حكمٌ، والحكمُ بعد القياس (٢١٣).
--
-- ── ⚠️ حدُّ ما يقوله هذا الملفّ ────────────────────────────────────────────
--
-- ① **مخطَّطُ `public` وحدَه.** فدوالُّ `auth` و`storage` و`extensions`
--    خارجَ المدى — **مدًى لم يُقَس، لا مدًى فارغ.**
--
-- ② **و`proconfig` يُظهر ما ثُبّت على الدالّة**، لا ما يرثه الاتّصال.
--    فدالّةٌ بلا `proconfig` تعمل بـ`search_path` الجلسة، وهو يتغيّر
--    بالمُتّصل. ⇒ **فـ«—» تعني «غيرُ مثبَّت»، لا «فارغ».**
--
-- ③ **ولا يقرأ الجسد.** دالّةٌ تؤهّل كلَّ أسمائها (`public.t`) لا يضرّها
--    `search_path`، وهذا المسحُ لا يفرّق. ⇒ **فالصفُّ مادّةٌ للحكم لا حكم.**
--
-- ④ **ولا يقيس من يستدعيها.** «من يستدعي» يلزمه مسحُ الشيفرة والمشغِّلات
--    معًا، وهو قياسٌ آخرُ لم يُطلَب هنا بعدُ.
--
-- ── 📌 التوقُّعُ، مُعلَنٌ قبل التشغيل، ومُشتقٌّ من نصّ المستودع ───────────────
--
-- مسحٌ على `docs/sql` (١٦٨ ملفًّا) أخرج **أربعَ دوالَّ متمايزةٍ** يُعلَن فيها
-- `security definer` نصًّا، بخمسة تعريفات:
--
--   public.freeze_consignment_after_use     set search_path = public
--   public.refuse_archiving_stocked_storage set search_path = public
--   public.refuse_unlinking_stocked_folder  set search_path = public
--   public.transfer_stock                   بلا `set search_path`
--
-- ⟹ **فأتوقّع أربعةً على الأقلّ بـ`prosecdef = true`، وثلاثةً منها
--    `search_path=public`، وواحدًا بلا `proconfig`.**
-- 🔴 **والمسجَّلُ عند المراجع «خمسٌ»، وهذا المسحُ أخرج أربعًا** — والفرقُ
--    خبرٌ: إمّا تعريفٌ لم يُودَع، أو عدٌّ للتعريفات لا للأسماء (خمسةُ
--    تعريفاتٍ لأربعة أسماء)، أو دالّةٌ في الإنتاج لا نصَّ لها عندنا.
--    ⇒ **ويحسمه هذا التشغيل، ولا يُحسم بالنصّ.**
-- ⚠️ **ومسحُ النصّ يطابق ألفاظًا ولا يحلّل SQL** ⟹ فرزٌ يفشل مفتوحًا،
--    والأربعةُ حدٌّ أدنى.
--
-- ==========================================================================

select
  p.proname                                        as "الدالّة",
  pg_get_function_identity_arguments(p.oid)        as "المعاملات",
  p.prosecdef                                      as "security definer",
  coalesce(array_to_string(p.proconfig, '  |  '), '—')
                                                   as "الضبطُ المثبَّت",
  pg_get_userbyid(p.proowner)                      as "المالك",
  l.lanname                                        as "اللغة",
  case p.prokind when 'f' then 'دالّة'
                 when 'p' then 'إجراء'
                 when 'a' then 'تجميعيّة'
                 when 'w' then 'نافذيّة'
                 else p.prokind::text end          as "الصنف",
  (select count(*) from pg_trigger t
    where t.tgfoid = p.oid and not t.tgisinternal) as "مشغِّلاتٌ تستدعيها"
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
join pg_language  l on l.oid = p.prolang
where n.nspname = 'public'
order by p.prosecdef desc, (p.proconfig is null) desc, p.proname;
