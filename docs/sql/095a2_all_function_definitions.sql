-- ==========================================================================
-- ٠٩٥أ٢ — قراءةٌ فقط، **جملةُ `select` واحدة**. لا يكتب شيئًا.
--
-- 🔴 مُجهَّزٌ ولم أشغّله. آمنٌ في أيِّ وقتٍ وقابلٌ للتكرار.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر وRLS متجاوَزة** — ولا أثرَ لذلك هنا:
-- `pg_proc` كتالوجٌ لا جدولَ صفوفٍ، ويُقرأ كاملًا بأيّ دور. **ويُقال كي لا
-- يُقرأ نجاحُه إثباتًا لشيءٍ عن العزل.**
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ما هو، ولماذا هو ملفٌّ ثانٍ بدل تعديل ٠٩٥أ
--
-- هو ٠٩٥أ **بلا سطر `and p.proname in (…)` وحدَه** — أي الاستعلامُ المكتوبُ
-- برأس `docs/db-functions.sql` حرفًا بحرف.
--
-- **و٠٩٥أ شُغِّل، فلا يُعدَّل بمكانه:** «السكربتُ اللي اشتغل ما بينتصلّح
-- بمكانه — والملفُّ هو السجلُّ الوحيد لما انلصق فعلًا». فالتغييرُ ينزل بملفٍّ
-- جديدٍ يقرأ الحالة.
--
-- ---------------------------------------------------------------------------
-- 🔴 والغرضُ سدُّ ثغرةٍ موصوفةٍ بترويسة `db-functions.sql` بلفظها
--
--   «١٩ دالّة، ولا وحدة منهن من موديول المخزون… **والضرر مش النقص، الضرر إن
--    الملف بيدّعي إنه صورة طبق الأصل**… **والغائب من هون ما بيثبت إشي عن
--    القاعدة.**»
--
-- ⇒ **يُلصق مخرَجُ العمود `definitions` مكانَ كلِّ شيءٍ تحت رأس ذلك الملفّ** —
-- الرأسُ يبقى، وما تحته يُستبدل بالكامل. **ولا يُحرَّر سطرٌ منه بيد:** «ما
-- بينكتب بالإيد — بينولّد، والاستعلام برأس الملف».
--
-- ---------------------------------------------------------------------------
-- المتوقَّع، **ويُقرأ العدُّ قبل النصّ**
--
--   `functions_found` ≈ **١٩ + دوالُّ المخزون** — أي أكثرُ من ١٩ قطعًا.
--
-- ⚠️ **ورقمٌ يساوي ١٩ بالضبط خبرٌ لا اطمئنان:** يعني أن الاستعلامَ لم يرَ
-- دوالَّ المخزون، **وهو نفسُه الاستعلامُ الذي أرجع أربعًا منها في ٠٩٥أ** —
-- فتناقضُهما يُحسَم قبل لصق أيِّ شيء.
--
-- ⚠️ **وشرطُ `pg_depend` لا يُحذف:** يستثني دوالَّ الامتدادات، وبدونه يطلع
-- الملفُّ ١٤٥ دالّة تغرق فيها التي لنا بين ~١٢٦ دالّةَ `gbt_*` من `btree_gist`.
-- **والاستثناءُ بالتبعيّة لا بنمط الاسم:** النمطُ يلزمه تحديثٌ مع كلّ امتدادٍ
-- جديد، والتبعيّةُ لا.
-- ==========================================================================

select
  count(*)                                                          as functions_found,
  string_agg(pg_get_functiondef(p.oid), E'\n\n' order by p.proname) as definitions
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public'
  and p.prokind in ('f', 'p')
  and not exists (
    select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e'
  );
