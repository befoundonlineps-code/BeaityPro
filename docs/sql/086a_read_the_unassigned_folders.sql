-- ٠٨٦أ — قراءةُ المجلّدات غير المُسنَدة قبل إسنادها
--
-- 🔴 استعلامُ قراءةٍ خالص. ولا جملةَ DDL ولا كتابةَ صفٍّ واحد — فالبند ١ من
-- CLAUDE.md مستوفًى بلا شرط: ما في شي هون يقدر يُسقط تغييرًا، لأن ما في تغيير.
-- الكتابةُ كلُّها في ٠٨٦ب، وتُكتب **بعد** وصول مخرَج هذا الملفّ لا قبله.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 ليش سكربتٌ لمرّةٍ واحدة، لا حقلٌ دائمٌ بالواجهة
-- ═══════════════════════════════════════════════════════════════════════════
--
-- بعد قاعدةِ الاشتقاق (lib/folderStorageInherit.js) صار `storage_id IS NULL`
-- **حالةً مقفلة**، وهذا مقيسٌ من ثلاثة أبواب لا من نيّة:
--
--   زرُّ «إضافة مجلّد»   معطَّلٌ حيث لا سياقَ يُشتقّ منه
--   نافذةُ المجلّد       بترفض الحفظ إن غاب السياق بعد الفتح
--   التعديل              ما بيبعت `storage_id` إطلاقًا، فما بيقدر يمسح ولا يملأ
--
-- ⇒ فالمجلّدُ الجديد بياخد مستودعًا أو ما بينخلق، **والموجودون اليوم هم كلُّ من
--   سيوجد بهذه الحالة، للأبد.** وواجهةٌ دائمةٌ لإسنادهم هي زرٌّ ما رح ينضغط
--   مرّةً تانية بعد الأولى.
--
-- ⚠️ **والبديلُ المعروض لو فُضِّلت الشاشة:** حقلُ مستودعٍ بنافذة التعديل بيظهر
-- **فقط** ما دام المجلّدُ غيرَ مُسنَد وبيختفي بنفسه بعد أوّل استعمال. أنظفُ من
-- زرٍّ دائم، **وأثقلُ من سكربتٍ لثلاثة صفوف** — والقرارُ للمالك.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 شاهدُ الصدق — مبنيٌّ بالسؤال لا مُستنقَذًا من الصدفة (§1ج · §4ب)
-- ═══════════════════════════════════════════════════════════════════════════
--
-- سؤالُ «مين غيرُ مُسنَد؟» جوابُه الفارغ إله معنيان ما بينفرقوا: ما في، أو
-- الاستعلامُ ما وصل الموضع. فالقسم B **ما بيصفّي على `storage_id is null`
-- إطلاقًا** — بيسرد **كلَّ** المجلّدات ومعها مستودعُ كلٍّ منها، **وتُصفّى
-- بالعين**. وعندها «ثلاثةٌ بلا مستودع» رقمٌ مقروءٌ من قائمةٍ كاملة لا مخرجُ
-- مرشِّح.
--
-- والقسم F بيجمع الأعداد بصفٍّ واحد: لو قال القسمُ B أربعةَ صفوفٍ وقال F
-- `المجلّدات: 4` فالاتنان بيقفلوا. ولو رجع B فاضيًا وF بيقول `المجلّدات: 0`
-- فالخبرُ «ما في مجلّدات» لا «ما لقيت».
--
-- والقسم A بيعدّ المجلّدات **لكلّ صالون**: المحرّرُ بيتخطّى RLS، فلو ظهر أكتر
-- من صفٍّ هون فالقوائمُ تحته مخلوطةٌ بين صالونين — وهاد لازم يُشاف قبل ما
-- يُكتب ٠٨٦ب لا بعده.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ما ينفع فيه هذا المخرَج
-- ═══════════════════════════════════════════════════════════════════════════
--
--   A  الصالونات كما يراها المحرّر — الشاهد أعلاه.
--   B  **كلُّ** المجلّدات: المعرِّف · الاسم · الأب · حيٌّ أم مؤرشَف · عددُ
--      منتجاته المباشرة · ومستودعُه أو «⛔ بلا مستودع».
--   C  منتجاتُ المجلّدات غير المُسنَدة **بأسمائها** — لأن «شامبو، بلسم» بتقول
--      لأيّ مستودعٍ يتبع المجلّد أوضح بكتير من عدد.
--   D  🔴 **البيّنةُ المقيسة:** وين لبضاعة هالمجلّدات رصيدٌ فعليٌّ الآن، مقروءًا
--      من `product_balances` — أي **نفسُ الرقم اللي بتعرضه الشاشة**. مجلّدٌ كلُّ
--      رصيدِ منتجاته في مستودعٍ واحد بيجاوب عن نفسه، فالسؤالُ بينتقل من الذاكرة
--      للبيانات.
--      ⚠️ وغيابُ صفٍّ هون ما بيعني «المجلّد فاضي» — بيعني **ما تحرّكت بضاعتُه
--      قطّ**، وعندها القرارُ للمالك وحده وما في بيّنةٌ تسنده.
--   E  المستودعات بمعرِّفاتها — ٠٨٦ب بيكتب `UPDATE` **بالمعرِّفات لا بالأسماء**
--      (§4: الفحصُ الحاسم ما بيعتمد على مطابقة أسماء؛ اسمٌ بحرفٍ زائد بيخلّي
--      الجملةَ تمرق بلا ما تصيب صفًّا وبلا ما تشتكي).
--   F  الأعدادُ مجتمعةً.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ⚠️ وما لا يُثبته — كي لا يُقرأ أوسعَ مما هو
-- ═══════════════════════════════════════════════════════════════════════════
--
-- محرّرُ SQL ما بيحمل JWT، فـ**`auth.uid()` فاضيةٌ فيه و RLS متجاوَزةٌ بالكامل**.
-- فكلُّ ما تحت بيسرد صفوفَ القاعدة كلَّها لا ما يراه صالون، **ونجاحُ هذا السكربت
-- ما بيثبت ولا شي عن العزل** — بيثبت الأشكالَ والأعداد فقط.

with
folders as (
  select
    pc.id,
    pc.salon_id,
    pc.name,
    pc.parent_id,
    pc.is_active,
    pc.storage_id
  from public.product_categories pc
),
direct_products as (
  select p.category_id, count(*) as n
  from public.products p
  group by p.category_id
)

select
  'A. الصالونات كما يراها المحرّر (RLS متجاوَزة)'::text        as section,
  f.salon_id::text                                             as id,
  '—'::text                                                    as name,
  ('المجلّدات: ' || count(*)::text)::text                       as detail,
  ('غير المُسنَدة: ' || count(*) filter (where f.storage_id is null)::text)::text as extra
from folders f
group by f.salon_id

union all

-- 🔴 بلا أيّ تصفيةٍ على `storage_id` — الفئةُ كاملةً، وتُصفّى بالعين.
select
  'B. كلُّ المجلّدات — الفئةُ كاملةً'::text,
  f.id::text,
  f.name::text,
  (
    'الأب: ' || coalesce(parent.name, '— جذر')
    || '  ·  ' || case when f.is_active is false then 'مؤرشَف' else 'حيّ' end
    || '  ·  منتجات مباشرة: ' || coalesce(dp.n, 0)::text
  )::text,
  coalesce(st.name, '⛔ بلا مستودع')::text
from folders f
left join folders parent on parent.id = f.parent_id
left join public.storages st on st.id = f.storage_id
left join direct_products dp on dp.category_id = f.id

union all

select
  'C. منتجاتُ المجلّدات غير المُسنَدة، بأسمائها'::text,
  f.id::text,
  f.name::text,
  p.name::text,
  case when p.is_active is false then 'مؤرشَف' else 'حيّ' end::text
from folders f
join public.products p on p.category_id = f.id
where f.storage_id is null

union all

-- 🔴 البيّنةُ المقيسة: وين لبضاعةِ هالمجلّدات رصيدٌ فعليٌّ الآن.
select
  'D. وين لبضاعتها رصيدٌ فعلًا (product_balances)'::text,
  f.id::text,
  f.name::text,
  coalesce(st.name, '⛔ مستودعٌ غيرُ معروف: ' || b.storage_id::text)::text,
  ('الرصيد الإجماليّ: ' || sum(b.balance_base)::text
   || '  ·  المنتجات: ' || count(distinct p.id)::text)::text
from folders f
join public.products p on p.category_id = f.id
join public.product_balances b on b.product_id = p.id
left join public.storages st on st.id = b.storage_id
where f.storage_id is null
group by f.id, f.name, st.name, b.storage_id

union all

select
  'E. المستودعات بمعرِّفاتها — ٠٨٦ب بيكتب بها لا بالأسماء'::text,
  s.id::text,
  s.name::text,
  case when s.is_active is false then 'مؤرشَف' else 'حيّ' end::text,
  '—'::text
from public.storages s

union all

select
  'F. شاهدُ الصدق — الأعدادُ مجتمعةً'::text,
  '—'::text,
  'الإجمالي'::text,
  (
    'المجلّدات: ' || (select count(*) from folders)::text
    || '  ·  غير المُسنَدة: ' || (select count(*) from folders where storage_id is null)::text
    || '  ·  المستودعات: ' || (select count(*) from public.storages)::text
  )::text,
  ('المنتجات: ' || (select count(*) from public.products)::text)::text

order by 1, 3, 4;
