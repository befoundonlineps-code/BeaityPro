create or replace view public.stock_fine_voidness
  with (security_invoker = true)
as
select
  f.id           as fine_id,
  f.salon_id,
  f.document_id,
  f.storage_id,
  f.employee_id,
  f.attribution,
  f.resolution,
  f.role_at_resolution,
  f.fine_percent,
  f.fine_basis,
  f.created_at,

  -- 🔴 الشرطُ **داخل الصفّ لا على النتيجة** — وهو موضعُ الحرفين الذي يُبقي
  -- العدمَ عدمًا. ولا `not is_live`: تلك تُقصي مستندَ العكس نفسَه، واللغوُ لا.
  (select l.reversed_by_document_id is not null
     from public.stock_document_liveness l
    where l.document_id = f.document_id
      and l.salon_id    = f.salon_id) as is_void,

  -- ومَن ألغاها — نفسُ الحقل الذي يُشتقّ منه العمودُ أعلاه، فلا يتنافران.
  (select l.reversed_by_document_id
     from public.stock_document_liveness l
    where l.document_id = f.document_id
      and l.salon_id    = f.salon_id) as voided_by_document_id

from public.stock_fines f;

