--
-- ⚠️ والجمل الأربع أدناه معاملةٌ واحدة عمدًا: لو رفض القيدُ صفوفًا قائمة وجب
-- أن يذهب العمودُ معه. الذرّيّةُ في الـDDL ميزةٌ لا خطر.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ✅ مبنيٌّ على ٠٨٤ — مقروءًا لا مفترَضًا
-- ═══════════════════════════════════════════════════════════════════════════
--
--   القسم A   سبعةُ أعمدةٍ على `product_categories`، **ولا واحدَ منها
--             `storage_id`**. وظهرت `parent_id` و`is_active` — أي أن
--             الاستعلامَ رأى الجدول، فالغيابُ خبرٌ لا صمت.
--
--   القسم B   `storages_id_salon_id_key  UNIQUE (id, salon_id)` ✅
--             ⇒ المفتاحُ المركّبُ ممكنٌ بلا إضافةِ أيّ فهرس.
--
--   القسم C   `product_categories_parent_id_salon_id_fkey`
--             `FOREIGN KEY (parent_id, salon_id) REFERENCES
--              product_categories(id, salon_id) ON DELETE RESTRICT`
--             ⇒ **النمطُ مستعملٌ في هذا الجدول نفسه**، فما يُكتب أدناه اتّباعٌ
--               لا اختراع. وفي `storages` نمطٌ ثالثٌ منه
--               (`owner_employee_id, salon_id → employees`).
--
--   القسم E   ثلاثةُ مجلّدات، **واحدٌ منها مُعشَّش** ⇒ «العمودُ الفقريّ» في
--             lib/folderStorageScope.js حالةٌ قائمةٌ لا نظريّة.
--
--   القسم F   مستودعان، كلاهما حيّ.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 ON DELETE — واقتراحُ المراجع (`SET NULL`) لا يمكن كتابتُه كما هو
-- ═══════════════════════════════════════════════════════════════════════════
--
-- الاقتراح: «يرجعوا غيرَ مُسنَدين، لا RESTRICT الذي يمنع حذفَ المستودع». والنيّةُ
-- صحيحة. لكنّ الصيغةَ المباشرة تفعل شيئًا آخر:
--
--   ⚠️ `ON DELETE SET NULL` على مفتاحٍ **مركّب** يُصفّر **كلَّ** أعمدة المفتاح —
--      أي `storage_id` **و`salon_id` معًا**. و`salon_id` هو `NOT NULL`
--      (القسم A). فالحذفُ يفشل بـ«null value in column salon_id»، أي يتصرّف
--      تصرُّفَ RESTRICT **برسالةٍ تبدو عطلًا في مخطّطنا**.
--
--   الصيغةُ التي تفعل المقصود هي `ON DELETE SET NULL (storage_id)` — قائمةُ
--   أعمدةٍ على الفعل — **وهي من PostgreSQL 15 فصاعدًا**، ولم أقِس إصدارَ هذا
--   الخادم. وسكربتٌ يفشل عند المالك يكلّف جولةً كاملة، فلا يُبنى على غير مقيس.
--
-- ⚠️ **والأهمّ: المستودعُ لا يُحذف أصلًا.** `DATABASE_DIAGRAM.md` يسجّل أن غيابَ
-- سياسة `delete` عن `storages` **قرارٌ لا سهو**، والأرشفةُ (`is_active`) هي
-- الطريقُ الوحيد. فاعتراضُ المراجع على RESTRICT — «يمنع حذفَ المستودع» — عن
-- طريقٍ مسدودٍ من جهةٍ أخرى أصلًا. (وهذه قراءةُ وثيقة لا قياس؛ ٠٨٥ب يقرأ
-- `pg_policies` ليحسمها.)
--
-- ⇒ **المكتوبُ هنا `ON DELETE RESTRICT`، وهو صحيحٌ تحت القراءتين معًا:** إن لم
--   تكن هناك سياسةُ حذفٍ فهو لا ينطلق أبدًا، وإن كانت فهو يحمي. وهو نفسُ ما
--   يفعله المفتاحان المركّبان الآخران في هذا المخطّط.
--
--   وإن فضّلتَ `SET NULL` بعد قراءة ما سبق، فالتغييرُ سطرٌ واحد **بشرط أن يكون
--   الخادمُ PostgreSQL ≥ 15**:
--
--       ON DELETE SET NULL (storage_id)
--
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.product_categories
  add column storage_id uuid;

-- ⚠️ NULLABLE عمدًا. `NULL` = **غيرُ مُسنَد**، ويظهر تحت «كل المستودعات» وحدها.
-- والبديلُ — إسنادُ الثلاثة القائمة إلى مستودعٍ افتراضيّ — يكتب ادّعاءً عن
-- بياناتٍ لا نعرفها: أيُّ مستودعٍ يخصّ «عناية بالشعر»؟ لا شيء في القاعدة يقول،
-- **وقيمةٌ افتراضيّةٌ تُقرأ بعد شهرٍ قرارًا اتُّخذ.** وهو نفسُ صنف البند ٨:
-- `default` على عمودٍ جديد يكتب جملةً عن كلّ صفٍّ قائم.

alter table public.product_categories
  add constraint product_categories_storage_id_salon_id_fkey
  foreign key (storage_id, salon_id)
  references public.storages (id, salon_id)
  on delete restrict;

-- فهرسٌ على العمود الجديد: كلُّ فتحةٍ للشجرة تصفّي به.
-- ⚠️ وليس `unique` — عدّةُ مجلّداتٍ لمستودعٍ واحد هي الحالةُ الطبيعيّة (أربعةٌ
-- في اللقطة الأولى للمرجعيّة).
create index if not exists idx_product_categories_storage
  on public.product_categories (storage_id);

-- ⚠️ نصٌّ عربيٌّ يُشحن إلى القاعدة — يقرأه من يفتح الجدول بأدوات القاعدة، لا من
-- يقرأ هذا الملفّ. و٠٨٥ب يقرأه راجعًا بـ`col_description`، وهي قاعدةُ المشروع:
-- ما يُشحن إلى مكانٍ لا نراه يُقرأ منه.
comment on column public.product_categories.storage_id is
  'المستودع الذي يتبع له هذا المجلّد. NULL = غير مُسنَد، فيظهر تحت «كل المستودعات» وحدها ولا يظهر تحت أيّ مستودع بعينه. لا يغيّر حسابَ الأرصدة إطلاقًا — الرصيدُ يُحسب من الحركات ولا يعرف بالمجلّدات.';
