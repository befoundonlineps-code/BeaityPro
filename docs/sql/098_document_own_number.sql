-- ٠٩٨ — رقمُ المستند الذي نكتبه نحن. **تغييرٌ فقط، ولا `select` في الملفّ.**
--       والتحقّقُ ٠٩٨ب.
--
-- 🔴 مُجهَّزٌ ولم أشغّله. المالكُ ينفّذه بيده بعد مراجعته.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر وRLS متجاوَزة** — والعمودُ لا يمسّ العزل
-- بحال. **يُقال كي لا يُقرأ نجاحُ التشغيل إثباتًا لشيءٍ عنه.**
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 ولماذا `doc_number` لا `write_off_doc_number` — **توسيعٌ لصياغتك أُعلنه**
--
-- قلتَ «عمودُه الخاصُّ بمعنى رقمِ مستند الشطب». **والاسمُ هنا أعمُّ**، وأطلب
-- تأكيدَه قبل التشغيل:
--
--   `supplier_doc_number` (٠٤٧)  رقمٌ **على ورقة المورّد** — كتبه هو
--   `doc_number`        (هذا)    رقمٌ **على مستندنا نحن** — كتبناه له
--
-- **والفرقُ ليس النوعَ بل صاحبَ الورقة.** وشاشةُ المرجع تعرض «Invoice №» على
-- الشطب **وعلى غيره**، فعمودٌ باسم الشطب يجعل الإرجاعَ يطلب عمودًا ثانيًا بنفس
-- المعنى بعد أسابيع — **وعمودان لمعنًى واحدٍ هما ما يلاحقه هذا المشروع.**
--
-- ⚠️ **والخطرُ المقابلُ مذكورٌ لا مُنكَر:** اسمٌ عامٌّ يُستعمل لاحقًا لغير ما وُضع
-- له. **والوصفُ المشحونُ أدناه هو ما يمنع ذلك** — يُقرأ بأدوات القاعدة ويقول
-- الحدَّ صراحةً.
--
-- ---------------------------------------------------------------------------
-- 🔴 تنبيهٌ لا منع — قرارُ المالك، ومتّسقٌ مع القائم
--
-- **لا قيدَ تفرّد.** الشاشةُ تنبّه على التكرار كما تفعل شاشةُ التوريد مع
-- `supplier_doc_number`، **فلا يُحجب حفظٌ مشروع.**
--
-- ✅ **والصرامةُ تبقى ممكنةً بلا كلفةٍ متى قُرِّرت:** الجدولُ لا يحمل رقمًا واحدًا
-- اليوم، **فقيدٌ يُضاف غدًا لا يجد ما ينظّفه.** وهذا هو ترتيبُ القرارات الصحيح:
-- الأوسعُ أوّلًا، والتضييقُ حين يُطلب — لا العكس.
--
-- ---------------------------------------------------------------------------
-- ⚠️ ولا `default`، وهو بندُ ٨ حرفيًّا
--
-- عمودٌ جديدٌ بافتراضيٍّ **يكتب ادّعاءً عن كلّ صفٍّ قائم**. والجدولُ فارغٌ اليوم
-- فالافتراضيُّ يكذب على العدم، **ويصير كذبًا حقيقيًّا يوم يمتلئ.**
--
-- ✅ **والقيدُ الوحيدُ يمنع تهجئتين للفراغ** — `null` أو نصٌّ فيه حرف، **ولا
-- `''`**. وفرعُ `is null` مكتوبٌ صراحةً لأن `CHECK` لا يرفض إلّا على `FALSE`،
-- فمقارنةُ العدم تُرجع UNKNOWN وتمرّ. **وهو الصنفُ الذي أصلحناه في ٠٤٤ و٠٥٦.**
-- ==========================================================================

alter table public.stock_documents
  add column if not exists doc_number text;

alter table public.stock_documents
  drop constraint if exists stock_documents_doc_number_check;

alter table public.stock_documents
  add constraint stock_documents_doc_number_check
  check (doc_number is null or length(btrim(doc_number)) > 0);

comment on column public.stock_documents.doc_number is
  'الرقمُ الذي نكتبه نحن على مستندنا — يكتبه إنسانٌ بيده، ولا يُولَّد تلقائيًّا (مقيسٌ على التطبيق المرجعيّ: كلُّ الأرقام هناك يدويّة). ⚠️ وليس supplier_doc_number: ذاك رقمٌ على ورقة المورّد كتبها هو، وهذا رقمٌ على ورقتنا. والفرقُ صاحبُ الورقة لا نوعُ المستند. ⚠️ ولا تفرُّدَ عليه بقرارٍ صريح: الشاشةُ تنبّه على التكرار ولا تمنعه، فلا يُحجب حفظٌ مشروع — وقيدُ التفرّد يبقى ممكنًا بلا كلفةٍ ما دام الجدولُ يُملأ من اليوم. واختيارُه اختياريٌّ دائمًا: مستندٌ بلا رقمٍ يُحفظ، ولا يوجد للفراغ إلّا تهجئةٌ واحدة (null لا نصٌّ فارغ).';
