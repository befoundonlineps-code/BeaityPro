-- ==========================================================================
-- ٠٩٣ — قراءةٌ فقط. لا يكتب شيئًا ولا يقدر أن يُسقط تغييرًا.
--
-- 🔴 مُجهَّزٌ ولم أشغّله. آمنٌ في أيِّ وقتٍ وقابلٌ للتكرار.
--
-- ⚠️ **و`auth.uid()` فارغةٌ في المحرّر، وRLS متجاوَزةٌ** — فما يُعدُّ هنا صفوفُ
-- الصالونات كلِّها لا صالونًا واحدًا. **وهذا هو المطلوب بالضبط**: سؤالُ الترحيل
-- عن القاعدة كلِّها.
--
-- ---------------------------------------------------------------------------
-- لماذا: **«هل يوجد ما يُرحَّل؟» سؤالٌ لا يجيبه المستودع**
--
-- الانتقالُ من المتوسّط المرجّح إلى تكلفةِ الدفعة يغيّر معنى كلّ `unit_cost`
-- مختوم. **وحجمُ الشغل يتغيّر جذريًّا بجواب سؤالٍ واحد:** أهناك حركاتٌ حقيقيّةٌ
-- مختومةٌ بالمتوسّط، أم القاعدةُ فارغةٌ منذ ٠٨٩ فيُبدأ نظيفًا؟
--
-- ⚠️ **ولا يُستنتج من المحادثة.** ٠٨٩ فرّغ `stock_movements` و`stock_documents`،
-- **وبعده جرى تجريبٌ** — والفرقُ بين «صفر» و«بضعة صفوفٍ تجريبيّة» و«حركاتٌ
-- حقيقيّة» هو الفرقُ بين ثلاثةِ أحجامِ عملٍ مختلفة.
--
-- ---------------------------------------------------------------------------
-- المتوقَّع، مكتوبٌ قبل التشغيل كي لا يُقرأ المخرَجُ بأثرٍ رجعيّ
--
--   A  عددُ الحركات والمستندات بحسب النوع — صفرٌ يعني «ابدأ نظيفًا»
--   B  كم (مستودع، منتج) له رصيدٌ غيرُ صفريّ الآن
--   C  🔴 **الحاسم:** كم منتجًا وُرِّد بأكثرِ من سعرٍ في نفس المستودع
--      ⇒ هؤلاء وحدَهم مَن يختلف عندهم المتوسّطُ عن تكلفة الدفعة.
--      صفرٌ هنا يعني أن التحويلَ **لا يغيّر رقمًا واحدًا مخزَّنًا اليوم**.
--   D  كم حركةً موسومةً بتكلفةٍ مقدَّرة — أي لم تأتِ من ثمنٍ دُفع
-- ==========================================================================

-- A · ما هو المسجَّل أصلًا.
select
  'A · الحركات' as section,
  d.doc_type,
  count(distinct d.id)  as documents,
  count(m.id)           as movements,
  min(d.doc_date)::date as first_date,
  max(d.doc_date)::date as last_date
from public.stock_documents d
left join public.stock_movements m on m.document_id = d.id
group by d.doc_type
order by d.doc_type;

-- B · الأرصدةُ القائمةُ الآن، ومعها متوسّطُها الحاليّ.
--
-- ⚠️ يُقرأ من `stock_movements` مباشرةً لا من `product_balances`، **لأن السؤال
-- عن المادّة الخام لا عن العرض** — وview قد يُصفّي بـRLS أو يُعرَّف لاحقًا بغير
-- ما نظنّ.
select
  'B · الأرصدة' as section,
  count(*)                                as storage_product_pairs,
  count(*) filter (where balance <> 0)    as with_balance,
  count(*) filter (where balance < 0)     as negative_balance_expect_0
from (
  select storage_id, product_id, sum(quantity_base) as balance
  from public.stock_movements
  group by storage_id, product_id
) b;

-- C · 🔴 الحاسم: مَن وُرِّد بأكثرِ من سعرٍ في نفس المستودع.
--
-- **هؤلاء وحدَهم من يفترق عندهم المتوسّطُ المرجّح عن تكلفة الدفعة.** ومنتجٌ
-- وُرِّد مرّةً واحدةً — أو مرّاتٍ بنفس السعر — يعطي الرقمَ نفسَه بالنظامين،
-- فترحيلُه لا شيء.
--
-- ⚠️ **والحركاتُ الموجبةُ وحدَها**: الداخلُ هو ما يصنع دفعةً، والخارجُ يستهلكها.
select
  'C · أسعارٌ متعدّدة' as section,
  count(*) as products_with_more_than_one_cost
from (
  select storage_id, product_id
  from public.stock_movements
  where quantity_base > 0
  group by storage_id, product_id
  having count(distinct unit_cost) > 1
) x;

-- D · كم رقمًا مختومًا لم يأتِ من ثمنٍ دُفع فعلًا.
--
-- ⚠️ `cost_is_estimated` = نفيُ الدرجة الأولى. وهذه الصفوفُ **لن تتحسّن**
-- بالانتقال إلى الدفعات — لا دفعةَ لها أصلًا — فهي تقيس حدَّ ما يمكن أن يعطيه
-- أيُّ نظامِ تكلفة.
select
  'D · التكلفة المقدَّرة' as section,
  count(*)                                          as movements,
  count(*) filter (where cost_is_estimated)         as estimated,
  count(*) filter (where unit_cost = 0)             as zero_cost,
  round(avg(unit_cost), 4)                          as avg_unit_cost
from public.stock_movements;
