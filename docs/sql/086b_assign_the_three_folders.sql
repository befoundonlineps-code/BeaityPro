-- ٠٨٦ب — إسنادُ المجلّدات الثلاثة لمستودعاتها، مرّةً واحدةً وللأبد
--
-- 🔴 لا DDL دائمًا هنا إطلاقًا — ثلاثةُ `UPDATE` وحرّاسُها. فالبند ١ من
-- CLAUDE.md («لا تجمع DDL دائم مع أيّ جملةٍ تقدر تفشل») **لا ينطبق بمعناه
-- المُحذِّر، بل بمعناه المُطَمئِن**: هنا الفحصُ والتغييرُ كلاهما DML، وتراجُعُهما
-- معًا **هو المطلوب بالضبط** — الثلاثةُ تُكتب أو لا يُكتب واحدٌ منها. فكلُّ
-- `RAISE EXCEPTION` أدناه **ميزةٌ لا خطر.**
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 🔴 والسبب الذي بُني عليه هذا الملفّ كلُّه: `UPDATE 0` ينجح بصمت
-- ═══════════════════════════════════════════════════════════════════════════
--
-- معرِّفٌ بحرفٍ زائد يعطي `UPDATE 0` — **لا خطأ، ولا تحذير، ولا صفٌّ أحمر.**
-- ومحرّرُ SQL يقول «Success». وهي §4 بلبوسها الأخطر: هناك «مطابقةُ اسمٍ تفشل
-- بصمت فيسكت الفحصُ كلُّه»، وهنا **كتابةٌ لا تقع ويُبلَّغ عنها نجاحًا.**
--
-- ⇒ فكلُّ صفٍّ يُفحص قبل كتابته، ويُعدّ بعد كتابته، **ولا يوجد طريقٌ يمرّ من هنا
--   بلا أثر.** والحرّاسُ السبعة:
--
--   ①  المعرِّفُ موجود                    ⟵ وإلّا فالمجلّدُ ليس في القاعدة
--   ②  اسمُه يطابق اسمَ القرار            ⟵ الشاهدُ على أنّ المعرِّفَ هو المقصود
--   ③  غيرُ مُسنَدٍ الآن                   ⟵ وإلّا فالسكربتُ شُغّل، أو الحالُ تغيّر
--   ④  المستودعُ موجودٌ واسمُه يطابق
--   ⑤  المستودعُ والمجلّدُ بنفس الصالون   ⟵ المفتاحُ المركّبُ يرفض غيرَه برسالةٍ غامضة
--   ⑥  `ROW_COUNT = 1` لكلّ صفّ           ⟵ الحارسُ على `UPDATE 0`
--   ⑦  بعد الكتابة: لا مجلّدَ بلا مستودع، ولا مجلّدَ في مستودعٍ غير مستودع أبيه
--
-- ⚠️ **والمعرِّفُ هو الذي يقرّر، والاسمُ شاهدٌ عليه — لا العكس.** §4 تمنع أن
-- **يُنتقى** الصفُّ بالاسم، ولا تمنع أن يُتحقَّق به. والفرق كلُّ شيء: الانتقاءُ
-- بالاسم يفشل مفتوحًا (صفرُ صفوفٍ وسكوت)، والتحقّقُ به يفشل مغلقًا (استثناءٌ
-- يسمّي الاسمين معًا).
--
-- ⚠️ **وحدُّ الحارس ② يُقال:** يُثبت أن المعرِّفَ يشير إلى المجلّد الذي سمّاه
-- القرار. **ولا يثبت أن القرار سمّى المجلّدَ الصحيح** — تلك بيّنةٌ لا يملكها إلّا
-- من يعرف بضاعتَه. (والقسم D من ٠٨٦أ كان سيسندها بالأرصدة، وهو لم يُشغَّل.)
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ⚠️ إن أوقفه الحارس ② على اسم — فالمعرِّفاتُ على الأرجح سليمة
-- ═══════════════════════════════════════════════════════════════════════════
--
-- «تجريبي» كُتب في القرار مع شرحٍ بين قوسين («ابن عناية بالشعر»)، والقوسان
-- شرحُ كاتبٍ لا جزءٌ من الاسم — **وهذا افتراضٌ مني**. فإن كان الاسمُ المخزَّن
-- غيرَ ذلك، يقف السكربتُ ويطبع **الاسمين معًا**: ما في القاعدة وما في القرار.
-- عندها التصحيحُ سطرٌ واحد، ولا شيء كُتب.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ⚠️ وما لا يُثبته
-- ═══════════════════════════════════════════════════════════════════════════
--
-- محرّرُ SQL ما بيحمل JWT، فـ**`auth.uid()` فاضيةٌ فيه وRLS متجاوَزةٌ بالكامل**.
-- فنجاحُ هذا السكربت يثبت أنّ الصفوف كُتبت، **ولا يثبت ولا شي عن العزل** — ولا
-- أنّ الشاشةَ ستكتبها لو حاولت. والفحص ⑦ مقيَّدٌ بصالون المجلّدات الثلاثة
-- وحدَه، لأنّ المحرّرَ يرى صالوناتٍ أخرى لا شأنَ لهذا القرار بها.

do $$
declare
  m         record;
  v_folder  record;
  v_storage record;
  v_salon   uuid := null;
  v_rows    int  := 0;   -- كم صفًّا في القرار — يُعدّ ولا يُكتب بالإيد (§«اكتب الشرط لا العدد»)
  v_written int  := 0;   -- وكم صفًّا كُتب فعلًا
  v_n       int;
  v_left    int;
  v_spines  int;
begin

  -- 🔴 القائمةُ مكتوبةٌ مرّةً واحدة، وكلُّ حارسٍ يقرأ منها هي. نسختان من
  -- الخريطة — واحدةٌ للفحص وواحدةٌ للكتابة — هما الجوابان اللذان يتباعدان.
  for m in
    select *
    from (values
      ('e88154d7-0b83-4d58-a6dd-92a68b7386b0'::uuid, 'عناية بالشعر'::text,
       '32556a91-f07f-496e-aa0f-969fff2b9ac9'::uuid, 'مستودع تجريبي'::text),
      ('1d471a82-4145-4088-95e1-d719e3eadc1b'::uuid, 'تجريبي'::text,
       '32556a91-f07f-496e-aa0f-969fff2b9ac9'::uuid, 'مستودع تجريبي'::text),
      ('9a6a2c2f-b4c8-4d66-9513-73092512dbd4'::uuid, 'عناية بالجسم'::text,
       'e9918c71-20ea-4805-ae42-3826b15e5e1e'::uuid, 'مستودع عام'::text)
    ) as t(folder_id, folder_name, storage_id, storage_name)
  loop
    v_rows := v_rows + 1;

    -- ① المجلّدُ موجود
    select pc.id, pc.salon_id, pc.name, pc.parent_id, pc.storage_id
      into v_folder
      from public.product_categories pc
     where pc.id = m.folder_id;

    if not found then
      raise exception '⛔ ما في مجلّدٌ بهذا المعرِّف: % — والقرارُ بيسمّيه «%».',
        m.folder_id, m.folder_name;
    end if;

    -- ② واسمُه شاهدٌ على أنّ المعرِّفَ هو المقصود
    if btrim(v_folder.name) <> btrim(m.folder_name) then
      raise exception '⛔ الاسمُ ما بيطابق للمعرِّف %: بالقاعدة «%» وبالقرار «%». المعرِّفُ بيقرّر والاسمُ شاهدٌ عليه، فالخلافُ بيوقف السكربت بدل ما يكتب لصفٍّ تاني.',
        m.folder_id, v_folder.name, m.folder_name;
    end if;

    -- ③ غيرُ مُسنَدٍ الآن — والحالتان تُسمَّيان، فالرسالةُ تقول أيُّهما وقعت
    if v_folder.storage_id is not null then
      if v_folder.storage_id = m.storage_id then
        raise exception '⛔ المجلّد «%» مُسنَدٌ سلفًا لنفس المستودع — يعني السكربتُ شُغّل من قبل، وما في شي يُكتب. ما انكتب ولا صفّ.',
          v_folder.name;
      else
        raise exception '⛔ المجلّد «%» مُسنَدٌ سلفًا لمستودعٍ تانٍ (%) مش للمقصود (%) — حدا أو شي غيّره بعد القرار. وقّف وابصص قبل ما يُكتب فوقه.',
          v_folder.name, v_folder.storage_id, m.storage_id;
      end if;
    end if;

    -- ④ المستودعُ موجودٌ واسمُه شاهد
    select s.id, s.salon_id, s.name, s.is_active
      into v_storage
      from public.storages s
     where s.id = m.storage_id;

    if not found then
      raise exception '⛔ ما في مستودعٌ بهذا المعرِّف: % — والقرارُ بيسمّيه «%».',
        m.storage_id, m.storage_name;
    end if;

    if btrim(v_storage.name) <> btrim(m.storage_name) then
      raise exception '⛔ اسمُ المستودع ما بيطابق للمعرِّف %: بالقاعدة «%» وبالقرار «%».',
        m.storage_id, v_storage.name, m.storage_name;
    end if;

    -- ⑤ الصالونُ واحد — وإلّا رفضَ المفتاحُ المركّبُ برسالةٍ بتبان عطلًا بالمخطّط
    if v_storage.salon_id <> v_folder.salon_id then
      raise exception '⛔ المستودع «%» بصالونٍ غير صالون المجلّد «%». والمفتاحُ المركّب (storage_id, salon_id) بيرفضها برسالةٍ ما بتشرح نفسها، فبنوقف هون بدلها.',
        v_storage.name, v_folder.name;
    end if;

    if v_salon is null then
      v_salon := v_folder.salon_id;
    elsif v_salon <> v_folder.salon_id then
      raise exception '⛔ المجلّدات مش كلُّها بنفس الصالون (% و%) — والمحرّرُ بيتخطّى RLS فبيشوف كلَّ الصالونات. وقّف.',
        v_salon, v_folder.salon_id;
    end if;

    -- الكتابة
    update public.product_categories
       set storage_id = m.storage_id
     where id = m.folder_id;

    -- ⑥ الحارسُ على `UPDATE 0` — بيتفحّص لكلّ صفٍّ لا للمجموع، لأن مجموعًا
    --    صحيحًا ممكن يخفي صفرًا هون واتنين هناك.
    get diagnostics v_n = row_count;
    if v_n <> 1 then
      raise exception '⛔ الكتابةُ على «%» مسّت صفوفًا غير صفٍّ واحد (العدد: %). و`UPDATE 0` بينجح بصمت، فهاد الحارسُ الوحيد عليه.',
        m.folder_name, v_n;
    end if;
    v_written := v_written + v_n;
  end loop;

  if v_written <> v_rows then
    raise exception '⛔ صفوفُ القرار (العدد: %) ما بتساوي المكتوبة (العدد: %).',
      v_rows, v_written;
  end if;

  if v_salon is null then
    raise exception '⛔ ما مرّ ولا صفٍّ بالحلقة — القائمةُ فاضية، والسكربتُ ما عمل شي.';
  end if;

  -- ⑦أ ما ضلّ مجلّدٌ بلا مستودع بهذا الصالون
  select count(*) into v_left
    from public.product_categories pc
   where pc.salon_id = v_salon
     and pc.storage_id is null;

  if v_left <> 0 then
    raise exception '⛔ ضلّت مجلّداتٌ بلا مستودع بهذا الصالون بعد الإسناد (العدد: %) — يعني التلاتة ما كانوا كلَّ غير المُسنَدين، والقائمةُ ناقصة. ما انكتب ولا صفّ.',
      v_left;
  end if;

  -- ⑦ب ولا مجلّدٌ صار بمستودعٍ غير مستودع أبيه
  --
  -- 🔴 يُفحص على **الحالة الناتجة** لا على النيّة — أي على ما استقرّ في القاعدة
  -- بعد الكتابة، فلا يعتمد على اسمٍ ولا على ترتيبِ صفوف القرار.
  --
  -- ⚠️ وهذه الحالةُ **مدعومةٌ بالشاشة** (المجلّدُ المعلَّق يُعرض ولا يُختار)،
  -- فليست عطلًا في ذاتها. تُرفض هنا لأنها تخالف القرارَ المعلن حرفيًّا: «الأب
  -- وابنه قصدًا سوا بنفس المستودع». فإن أُريد خلافُ ذلك يومًا، حذفُ هذه الكتلة
  -- سطرٌ واحد — والرفضُ هنا ليس حكمًا على التصميم بل حراسةٌ لنيّةٍ مكتوبة.
  select count(*) into v_spines
    from public.product_categories c
    join public.product_categories p on p.id = c.parent_id
   where c.salon_id = v_salon
     and c.storage_id is distinct from p.storage_id;

  if v_spines <> 0 then
    raise exception '⛔ في مجلّداتٌ صارت بمستودعٍ غير مستودع أبيها (العدد: %) — والقرارُ بيقول إن الأبَ وابنَه سوا. ما انكتب ولا صفّ.',
      v_spines;
  end if;

end $$;

-- ═══════════════════════════════════════════════════════════════════════════
-- القراءةُ الراجعة — بسيطةٌ لدرجة ما تقدر تفشل
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ⚠️ بلا تجميعٍ وبلا `||` وبلا تحويلِ نوع، عمدًا: هي بنفس معاملة الكتابة، فأيُّ
-- فشلٍ فيها **يمحو الكتابة ويُبلّغ عن نفسه هو** (§1 بحرفه). فالحمايةُ الوحيدة
-- الممكنة أن تكون أبسط من أن تفشل.
--
-- ⚠️ وبلا تصفيةٍ على `storage_id` ولا على المعرِّفات الثلاثة — **كلُّ المجلّدات**،
-- فيُقرأ «التلاتة صاروا مُسنَدين» من قائمةٍ كاملة لا من مخرَجِ مرشِّحٍ يؤكّد ما
-- سأل عنه (§1ج).
--
-- المتوقَّع: ثلاثةُ صفوف، لا واحدَ منها `storage` فارغ، و«تجريبي» مع أبيه
-- «عناية بالشعر» على «مستودع تجريبي» — و`parent_storage` مطابقٌ لـ`storage`
-- حيث يوجد أب.

select
  pc.name         as folder,
  s.name          as storage,
  parent.name     as parent_folder,
  ps.name         as parent_storage,
  pc.id           as folder_id,
  pc.storage_id   as storage_id,
  pc.salon_id     as salon_id
from public.product_categories pc
left join public.storages s on s.id = pc.storage_id
left join public.product_categories parent on parent.id = pc.parent_id
left join public.storages ps on ps.id = parent.storage_id
order by pc.name;
