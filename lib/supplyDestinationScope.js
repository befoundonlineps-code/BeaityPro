// قاعدةُ تطابق الأصناف عند تغيير مستودعِ الوجهة — «توريد بضاعة».
//
// 🔴 **وهي قاعدةٌ جديدةٌ تمامًا، لا استعادةٌ لواحدةٍ قائمة.** قِيست قبل البناء:
// `storage_categories` تُقرأ في أربعة مواضعَ بكودِ التطبيق ولا واحدَ منها
// **يتقاطع فيه مستودعان**، و`transfer_stock` (٠٤٩ج) حرّاسُها خمسة — نفسُ
// المستودع · مستندٌ فارغ · مستودعٌ غيرُ موجود · منتجٌ غيرُ موجود · سطرٌ بصفر —
// **ولا ذكرَ للأصناف فيها إطلاقًا**.
//
// ⚠️ **والذي كان موجودًا جملةٌ عن الإمكان لا عن التنفيذ:** `storageFolders.js`
// يقول إن نموذج M:N بُني لأن «قيدَ التشكيلة لا يمكن التعبير عنه أصلًا حين يكون
// للمجلّد مستودعٌ واحد». **قابلًا للتعبير، لا معبَّرًا عنه.**
//
// ⚠️ **وهذا الملفُّ حارسُ شاشةٍ لا حارسُ قاعدة.** وحارسُ الواجهة ينحلّ بأوّل
// نداءٍ من مكانٍ آخر — فالحارسُ في القاعدة بندٌ منفصلٌ بقرار المالك، وغيابُه
// اليوم **يُقال هنا كي لا يُقرأ هذا الملفُّ ضمانةً**.

// مجلّداتُ مستودعٍ واحد.
export function folderIdsOfStorage(links, storageId) {
  const ids = new Set()
  if (!storageId) return ids
  for (const link of links || []) {
    if (link.storage_id === storageId) ids.add(link.category_id)
  }
  return ids
}

// 🔴 ما ينجو من الاختيار بعد تغيير الوجهة — **تقاطعٌ لا اتّحاد.**
//
// الحالاتُ الثلاثُ التي وصفها المالك ليست ثلاثةَ فروع، هي **تقاطعٌ واحد**:
//
//   الوجهةُ فيها كلُّ مجلّدات العدسة  ⟵ التقاطعُ = الاختيارُ كلُّه
//   فيها بعضُها                      ⟵ التقاطعُ = المشتركةُ وحدَها
//   ولا مجلّدَ مشترك                 ⟵ التقاطعُ فارغ
//
// ⚠️ **ومجلّداتُ الوجهةِ الخاصّةُ لا تظهر**، وهذا ما يجعله تقاطعًا لا اتّحادًا:
// الجدولُ يعرض ما اختاره المستخدمُ من عدسته، مصفًّى بما تقدر الوجهةُ أن تحفظه —
// لا ما تحفظه الوجهةُ وحدَها. **واتّحادٌ هنا يُدخل صفوفًا لم يؤشّرها أحد.**
export function scopedFolderIds({ selectedFolderIds, links, toStorageId } = {}) {
  const selected = selectedFolderIds || []
  // ⚠️ **لا وجهةَ = لا تضييق.** الحقلُ يُملأ افتراضيًّا بمستودع العدسة، وفراغُه
  // حالةٌ عابرةٌ أثناء التغيير — وتضييقٌ إلى لا شيءٍ عندها يُفرغ الجدولَ فجأةً
  // ويبدو عطلًا.
  if (!toStorageId) return selected

  const allowed = folderIdsOfStorage(links, toStorageId)
  return selected.filter((id) => allowed.has(id))
}

// 🔴 **ولا يُمسّ الاختيارُ المخزَّن — التضييقُ عرضٌ لا حذف.**
//
// ⚠️ هذا هو الفخُّ الذي يُبنى مرّةً ويُكتشف بعد شهر: لو صُفِّي الاختيارُ نفسُه
// عند كلّ تغييرِ وجهة، لكان تبديلُ الوجهةِ ذهابًا وإيابًا **يأكل المجلّدات
// واحدًا واحدًا** — الأولى تُسقط غيرَ المشترك، والرجوعُ لا يعيده لأنه لم يعد
// في الاختيار. **ولا رسالةَ خطأ ولا سطرَ يشتكي؛ الجدولُ ينقص فقط.**
//
// فالاختيارُ يبقى كما أُشّر، وهذه الدالّةُ تجيب على «ماذا يُرسم الآن».
export function destinationNarrows({ selectedFolderIds, links, toStorageId } = {}) {
  const selected = selectedFolderIds || []
  const kept = scopedFolderIds({ selectedFolderIds: selected, links, toStorageId })
  return {
    kept,
    hidden: selected.filter((id) => !kept.includes(id)),
    // ⚠️ **الفراغُ حالةٌ مشروعةٌ تُقال، لا شاشةٌ معطّلة.** «ما في مجلّدٌ مشترك»
    // خبرٌ يحتاج فعلًا يزيله (ربطُ الصنف بالوجهة)، وجدولٌ فارغٌ بلا جملةٍ
    // يُقرأ عطلًا — وهي قاعدةُ «الشرحُ يحمل: ما معناها · مثالٌ · كيف تختفي».
    empty: kept.length === 0 && selected.length > 0,
  }
}
