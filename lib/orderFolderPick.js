import { foldersForStorage, isPassThroughFolder } from './folderStorageScope'
import { folderTickRows } from './storageFolders'

// النافذةُ الأولى في «طلب بضاعة»: أيُّ مجلّداتِ هذا المستودعِ ندخل بها إلى
// الجدول.
//
// ⚠️ **وهي نافذةٌ لا خطوةٌ في نافذة.** المرجعُ يفتحها وحدَها ثمّ يغلقها إلى
// الجدول، و«إلغاء» فيها يلغي العمليّةَ كلَّها لا يرجع خطوةً — لأنه لا يوجد ما
// يُرجَع إليه.
//
// 🔴 **وهي مشتركةٌ بين أربع عمليّات، مقيسًا على التطبيق الحيّ:** طلب بضاعة ·
// توريد · شطب · إرجاع للمورّد. **وعنوانُها يتبع العمليّة** («…for supply» ·
// «…for write-off products» · «…for products return»).
//
// ⚠️ **ولهذا لا يحمل هذا الملفُّ عنوانًا ولا يعرف أيَّ عمليّةٍ استدعته:** العنوانُ
// هو عنوانُ `RefModal` المحيطة، أي اسمُ العمليّة من `OPERATION_LABEL_KEY`. فحين
// تُعاد للثلاث الباقية يصحّ عنوانُ كلٍّ منها **بالبناء** — بدل خريطةِ عناوينَ
// تُكتب بيد، وهي الشكلُ الذي يتقادم بصمتٍ في هذا المشروع أكثرَ من غيره.

// صفوفُ التأشير: مجلّداتُ المستودع بترتيب الشجرة، وأيُّها يقبل التأشير.
//
// 🔴 **المجلّدُ المعلَّق يُعرَض ولا يُؤشَّر** — وهي القاعدةُ المشحونةُ نفسُها في
// الشجرة، لا اجتهادٌ جديد. المعلَّقُ (pass-through) ليس من أصناف هذا المستودع؛
// هو أبٌ في الطريق إلى واحدٍ منها، فحذفُه يكسر التداخلَ ويجعل الابنَ يبدو جذرًا.
//
// ⚠️ **ولا يُطرح السؤالُ عليه أصلًا:** الطلبُ من مجلّدٍ لا يحفظه هذا المستودعُ
// طلبٌ لبضاعةٍ ليس لها مكانٌ تصل إليه — والقاعدةُ ترفض الربطَ نفسَه.
export function orderFolderRows({ categories, storageId, links } = {}) {
  const inStorage = foldersForStorage(categories, storageId, links)

  return folderTickRows(inStorage).map((row) => {
    const category = inStorage.find((c) => c.id === row.id)
    return {
      ...row,
      selectable: !isPassThroughFolder(category, storageId, links),
    }
  })
}

// كلُّ ما يقبل التأشير — وهو حالةُ الفتح الافتراضيّة.
//
// ⚠️ **الكلُّ مؤشَّرٌ عند الفتح، لا الفراغ.** هذا ما تعرضه لقطةُ المرجع، وهو
// أيضًا الاتّجاهُ الذي يُخطئ أرحمَ الخطأين: مَن فتح النافذةَ يريد أن يطلب، فبدءٌ
// بالكلّ يجعل عملَه شطبًا، وبدءٌ بالفراغ يجعله بحثًا. **وشاشةٌ تفتح على جدولٍ
// فارغٍ تبدو معطّلة.**
export function allSelectableIds(rows) {
  return (rows || []).filter((row) => row.selectable).map((row) => row.id)
}

// هل يُسمح بالمضيّ إلى الجدول.
//
// ⚠️ **ولا شيءَ مؤشَّرٌ ليس خطأً يُشرح، هو زرٌّ معطَّل.** رسالةُ رفضٍ عن «اختر
// مجلّدًا» تشرح ما تقوله الشاشةُ أصلًا؛ والزرُّ المعطَّل يقوله بلا كلام.
export function canOpenGrid(selectedIds) {
  return (selectedIds || []).length > 0
}

// تأشيرُ/شطبُ مجلّدٍ واحد — دالّةٌ نقيّةٌ تُرجع الاختيارَ الجديد.
//
// ⚠️ **ولا تُؤشَّر إلّا الصفوفُ القابلة.** بلا هذا الشرط يستطيع نداءٌ برمجيّ أن
// يُدخل معلَّقًا في الاختيار، فيصل الجدولَ مجلّدٌ لا يحفظه هذا المستودع — وهو
// بالضبط ما تمنعه الشاشةُ بصريًّا، مفتوحًا من الباب الخلفيّ.
export function toggleFolder(selectedIds, rows, id) {
  const row = (rows || []).find((r) => r.id === id)
  if (!row || !row.selectable) return selectedIds || []

  const current = new Set(selectedIds || [])
  if (current.has(id)) current.delete(id)
  else current.add(id)

  // بترتيب الصفوف لا بترتيب الضغط، فالجدولُ بعدها يقرأ ترتيبًا مستقرًّا.
  return (rows || []).filter((r) => current.has(r.id)).map((r) => r.id)
}
