// أشكالُ «هذا الملفُّ يقبل إدخالًا أو يرسل» — **موضعٌ واحدٌ يقرؤه حارسان.**
//
// 🔴 **وُلد هذا الملفُّ من عضّةِ حارسٍ سليم، لا من ترتيب:** حارسُ المال في
// `returnFillRepro.test.js` يقول عن نفسه «**والسؤالُ عن الشاشات التي يكتب فيها
// إنسانٌ مبلغًا**» — **ومداه كان «كلُّ ملفٍّ يذكر `paidAmount`».** فأوّلُ شاشةِ
// عرضٍ تعرض المبلغَ المستلَم سقطت تحته، **وهي لا تكتب شيئًا ولا يمكنها.**
//
// ⚠️ **والعلاجُ المغري كان تخفيفَه** — استثناءُ `components/documentView/`
// بالاسم. **وذلك ثقبٌ بلا قاع:** شاشةُ عرضٍ تكتب يومًا تمرّ لأن مجلّدَها
// مستثنًى، **وهو بالضبط ما وُضع الحارسُ ليمنعه.**
//
// ⇒ **فالمدى يُصوَّب إلى جملته:** «يكتب فيها إنسان» تعني **أن فيها ما يُكتب
// فيه** — وذلك مقيسٌ من النصّ، لا مسرودٌ بأسماء مجلّدات.
//
// ⚠️ **ونسخةٌ ثانيةٌ من القائمة كانت ستصير فرصةً ثانيةً لتتباعد** — و«أربعُ
// نسخٍ حرّةٍ في أن تتباعد» صنفٌ مكتوبٌ في `CLAUDE.md` بأربعة أمثلة. **فالقائمةُ
// هنا، والحارسان يستوردانها.**

// ⚠️ **التجريدُ قبل أيّ فحص:** التعليقُ الذي يشرح **لماذا** لا يوجد `<input>`
// يذكره بالاسم — **وحارسٌ يقرأ التعليقَ يعضّ الملفَّ لأنه وثّق قرارَه**، ويدفع
// لحذف الشرح إرضاءً لعدّاد.
export function stripComments(text) {
  return String(text)
    .split(/\r?\n/).map((line) => line.replace(/\/\/.*$/, '')).join('\n')
    .replace(/\/\*[\s\S]*?\*\//g, '')
}

// كلُّ ما يقبل إدخالًا أو يرسل — **بالشكل لا بقائمة أسماء العناصر.**
//
// ⚠️ **و`write` منها:** `RefTd` عرضٌ افتراضًا ولا تصير قابلةَ للكتابة إلّا
// بتمريرها صراحةً، **فتمريرُها في شاشة عرضٍ هو الثغرةُ نفسُها بلبوس خاصّيّة.**
// **وبحدود الكلمة** — وإلّا أسقط `rewriteCount` و`WriteOffDocumentView`.
export const INTERACTIVE = [
  ['<input', /<input\b/],
  ['<select', /<select\b/],
  ['<textarea', /<textarea\b/],
  ['<form', /<form\b/],
  ['<button', /<button\b/],
  ['NumberField', /\bNumberField\b/],
  ['خاصّيّة write', /\bwrite\b/],
  ['contentEditable', /contentEditable/],
  // ══════════════════════════════════════════════════════════════════
  // 🔴 **كلُّ معالِجِ حدثٍ — شكلًا لا قائمةَ أسماء**
  // ══════════════════════════════════════════════════════════════════
  //
  // **كان هنا اسمان: `onSubmit` و`onChange`.** ثمّ أُضيف `onClick` بعد أن
  // انكشف بالحقن، **ثمّ سأل المالكُ السؤالَ الصحيح:** «إذا `onClick` كان ناقص،
  // ممكن `onFocus` و`onBlur` و`onKeyDown` و`onMouseDown` وأمثالها تكون ناقصة
  // كمان. عدّدوا كلَّ أحداث React… مش بس يلي انكشف بالصدفة».
  //
  // ⚠️ **وتعدادُ الأسماء هو العطلُ نفسُه مؤجَّلًا** — `CLAUDE.md` يسمّيه:
  // «الحارسُ الذي يعدّ المعروف يفشل مفتوحًا، والذي يصف الشكلَ يفشل مغلقًا».
  // **وأنا عددتُ اسمين ففاتني ثالثٌ، وعدُّ ثلاثين يفوته الحادي والثلاثون** —
  // وReact تضيف أحداثًا بإصداراتها.
  //
  // ⇒ **فالشكلُ: أيُّ خاصّيّةٍ تبدأ بـ`on` يليها حرفٌ كبيرٌ ثمّ `=`.**
  // `onClick` · `onPointerDown` · `onKeyDown` · `onBlur` · `onWheel` ·
  // `onDrop` · `onTouchStart` · **وكلُّ ما لم يُخترع بعد.**
  //
  // ⚠️ **و`=` جزءٌ من الشكل عمدًا** — فذكرُ الاسم في تعليقٍ أو نصٍّ لا يُمسَك،
  // **وتمريرُه خاصّيّةً يُمسَك.** (والتعليقاتُ مجرَّدةٌ أصلًا، وهذا حدٌّ ثانٍ.)
  ['معالِجُ حدثٍ (on…=)', /\bon[A-Z][A-Za-z]*\s*=/],

  // 🔴 **والنشرُ يخبّئ ما لا يُقرأ** — `{...rest}` قد يحمل `onClick` بلا أن
  // يظهر اسمُه في الملفّ إطلاقًا. ⇒ **ممنوعٌ في شاشة عرضٍ**، وهي لا تحتاجه:
  // **صفرُ نشرٍ فيها اليوم، مقيسًا.**
  ['نشرُ خصائص ({...x})', /\{\s*\.\.\.[A-Za-z_$][\w$]*\s*\}/],
  // 🔴 **ونداءُ الترحيل نفسُه** — الحدُّ الأخير: شاشةُ عرضٍ لا تستورد ما يكتب.
  ['نداءُ ترحيل', /postStockDocument|reverseStockDocument|postStocktake|transferStock|saveProductOrder/],
]

// هل يقبل هذا النصُّ إدخالًا أو يرسل؟ — **يُجرَّد التعليقُ أوّلًا.**
export function isInteractive(source) {
  const body = stripComments(source)
  return INTERACTIVE.some(([, shape]) => shape.test(body))
}

// أسماءُ معالِجات الأحداث الموجودةِ فعلًا — **ليطبع الحارسُ ما قاسه بجانب ما
// حكم به**، فيقول «`onKeyDown`» لا «شكلٌ ممنوع».
//
// ⚠️ **وهي مقيسةٌ لا مسرودة:** تُستخرَج من النصّ، فتسمّي حدثًا لم يخطر ببال
// كاتب الحارس. **وهذا هو الفرق كلُّه.**
export function eventHandlersIn(source) {
  const found = stripComments(source).match(/\bon[A-Z][A-Za-z]*\s*=/g) || []
  return [...new Set(found.map((s) => s.replace(/\s*=$/, '')))].sort()
}
