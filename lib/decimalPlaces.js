// تقريبُ ما يُكتب بالإيد إلى خانتين — **وبإعلانٍ لا بصمت.**
//
// 🔴 قرارُ المالك بلفظه: «تقريب تلقائي لخانتين، مع رسالة واضحة توضح للمستخدم
// إنه تم تقريب الرقم — مو تقريب صامت. لازم يشوف بوضوح إنه اللي كتبه انغيّر
// ولشو.»
//
// والخطوةُ (`step="1"` للمال و`step="0.01"` للكمّيّة) تحكم **السهمَ وحدَه**؛
// والكتابةُ اليدويّة تمرّ من هنا. فالبابان اللذان يدخل منهما رقمٌ إلى الشاشة
// صار لهما جوابٌ واحد.
//
// ⚠️ **والصمتُ هو ما يُرفض، لا التقريب.** رقمٌ يتغيّر بلا أن يقول أحدٌ شيئًا هو
// نفسُ صنف «الشاشةُ تعرض حالةً قديمةً كأنها الحقيقة»: لا خطأ، ولا سطرَ يشتكي،
// ويكتشفه صاحبُه بعد شهرٍ في تقرير.

export const PLACES = 2

// 🔴 التقريبُ **بإزاحة الأُسّ نصًّا، لا بالضرب في مئة ولا بـ`toFixed`.**
//
// ⚠️ **والأمثلةُ أدناه مقيسةٌ على هذا المحرّك، لا مأخوذةٌ عن مقال** — وأوّلُ
// صياغةٍ لهذا التعليق سمّت الأرقامَ الخطأ: قالت إن `10.005` تنكسر بالضرب، وهي
// تعمل. **الذي ينكسر غيرُها:**
//
//   القيمة     × 100      toFixed(2)   إزاحةُ الأُسّ
//   1.005      1     ✗    1      ✗     1.01
//   1.015      1.01  ✗    1.01   ✗     1.02
//   2.675      2.68       2.67   ✗     2.68
//   0.615      0.62       0.61   ✗     0.62
//   10.005     10.01      10.01        10.01
//
// (`1.005 * 100` تساوي `100.49999999999999` بالثنائيّ، و`10.005 * 100` تساوي
// `1000.5000000000001` — ولذلك الأولى تنكسر والثانية لا. **والذاكرةُ لا تعرف
// أيَّهما.**)
//
// ✅ **والاتّجاهُ واحدٌ في كلّ الأخطاء: نحو الأصغر.** أي أن السعرَ يُقرَّب إلى
// الأسفل بصمت — وهو الاتّجاه الذي لا يشتكي منه أحد حتى يُجمَع ألفَ مرّة.
//
// وإزاحةُ الأُسّ بالنصّ (`'1.005' + 'e2'`) يقرأها المحلّلُ العدديّ رقمًا عشريًّا
// واحدًا، **فلا يقع الضربُ أصلًا.** والحالاتُ الخمس فوق محروسةٌ في
// lib/decimalPlaces.test.js، **ومعها الطريقتان المرفوضتان مكتوبتين** ليُرى
// خطؤهما بدل أن يُقترحا «تبسيطًا» بعد شهر.
function roundHalfUp(n, places) {
  const shifted = Math.round(Number(`${n}e${places}`))
  return Number(`${shifted}e-${places}`)
}

// كم خانةً عشريّةً كُتبت فعلًا.
//
// ⚠️ من **النصّ** لا من الرقم: `Number('10.50')` يساوي `10.5`، فالعدّ على الرقم
// يقول خانةً واحدة عن نصٍّ فيه اثنتان — والمستخدمُ لم يكتب زيادة، فلا شيء
// يُقرَّب ولا رسالةَ تظهر. **والسؤال عمّا كُتب، لا عمّا يساويه.**
export function decimalsIn(raw) {
  const text = String(raw ?? '').trim()
  const dot = text.indexOf('.')
  if (dot === -1) return 0
  return text.length - dot - 1
}

// 🔴 الجواب: النصُّ بعد التقريب، وهل تغيّر، ومن أيّ قيمة.
//
// ⚠️ **ولا يُقرَّب شيءٌ أثناء الكتابة.** يُنادى عند مغادرة الحقل: من يكتب
// «10.005» يمرّ حتمًا بـ«10.0» و«10.00»، وتقريبٌ عند كلّ ضغطةِ مفتاح يقاتل
// صاحبَه وهو في منتصف رقمِه.
//
// ⚠️ **والفراغُ يبقى فراغًا** — لا يصير صفرًا. هذا المشروع دفع ثمنَ
// `Number('') === 0` مرّتين: خانةٌ فارغة وصلت `0` واجتازت `v_cost >= 0`
// باقتدار، فصار «لا أعرف» رقمًا.
export function roundTyped(raw, places = PLACES) {
  const text = String(raw ?? '').trim()
  if (text === '') return { text: '', rounded: false, from: '' }

  const n = Number(text)
  if (!Number.isFinite(n)) return { text, rounded: false, from: text }
  if (decimalsIn(text) <= places) return { text, rounded: false, from: text }

  const value = roundHalfUp(n, places)
  // ⚠️ **يُقارَن الرقمُ لا النصّ.** `10.000` تُقصّ إلى `'10'` — والنصُّ تغيّر
  // والرقمُ لا. وإعلانُ تغييرٍ لم يقع **يُعلِّم القارئَ تجاهلَ الرسالة**، فتضيع
  // معها المرّةُ التي تغيّر فيها رقمُه فعلًا.
  return { text: String(value), rounded: value !== n, from: text }
}
