const fs = require('fs')
const path = require('path')

// كلُّ سكربتٍ مُودَعٍ له سطرُ حالة — وهذا هو حارسُ البند ١٠.
//
// ⚠️ الحادثة. البند ١٠ («السكربتُ يُودَع قبل أن يُشغَّل») دُمج في ٢٦ آب ٢٠٢٦
// **بلا حارس، عمدًا**: كان في `docs/sql` ١٦٧ ملفًّا و٥٥ منها بلا سطرِ حالةٍ
// إطلاقًا، فحارسٌ يُولد أحمرَ على خمسةٍ وخمسين يُولد ومعه قائمةُ استثناءٍ
// بأسمائها — وهي الشكلُ الذي كلّفنا مرارًا. فأُجّل حتّى يُملأ السجلّ.
//
// وقد مُلئ (٢٧ آب ٢٠٢٦): التغطيةُ ١٦٨ من ١٦٨ — **ومنها اثنان تغطيتُهما من
// مدًى يُعلن الغياب (`076` · `078`)، والحدُّ الخامسُ أدناه** — فيُولد
// أخضرَ بلا استثناءٍ
// واحد. **وذاك شرطُ ميلاد أيّ حارسٍ عندنا: حارسٌ يُولد أحمرَ يُطفأ في أوّل
// يومٍ مزدحم.**
//
// ⚠️ وحدُّ الرقم مكتوبٌ **داخلَ جملته** لا في فقرةٍ تليها، هنا وفي
// `CLAUDE.md` معًا. **وذلك مقصودٌ من الآن وإن لم يكن مقصودًا أوّلَ مرّة:**
// فقرةٌ فاصلةٌ تجعل الرقمَ قابلًا للاقتباس وحدَه، **والحدُّ الذي يُقتبس دونه
// حدٌّ لم يُكتب.**
// 🔴 وقد أُدرجت هذه الفقرةُ أوّلَ مرّةٍ **بين شطرَي الجملة التي فوقها** —
// فصارت «واحد.» تفتتح جملةً ولا معنى لها. **والفقرةُ التي تحرّم الفصلَ هي
// التي فصلت، في الجملة التي كُتبت لحمايتها.** ⇒ **فقاعدةٌ صحيحةٌ مكتوبةٌ لا
// تحرس كاتبَها لحظةَ كتابتها.** ولم يره فرقٌ ولا عددُ أسطرٍ ولا `numstat`:
// **الفرقُ يُظهر الأسطرَ ولا يُظهر الجُمل.**
//
// 🔴 واتّجاهُ الحراسة يُقال بحدّه، ولا يُوسَّع:
//
//   ✅ يحرس : ملفٌّ في `docs/sql` بلا سطرِ حالةٍ في `docs/sql/README.md`
//             ⟵ وهو الحالةُ التي يمنعها البند ١٠: يُودَع فيُنسى
//   🔴 لا يحرس : سطرُ حالةٍ لا يقابله ملفّ
//             ⟵ فأربعةُ صفوفٍ اليومَ لا تقابل ملفًّا **بحقّ**. والأمرُ
//               يُسمّى فيُعاد به القياسُ يومَ يتغيّر العدد، ولا يشيخ صامتًا:
//               `node -e` يقرأ صفوفَ الجداول ويُسقط ما يطابق رمزَ ملفٍّ —
//               وهو `rowToken`/`expand` أدناه بعينهما، على ملفّات `docs/sql`.
//               ⟹ أربعةٌ (٢٧ آب ٢٠٢٦): تشغيلٌ جرى بلا سكربتٍ مُودَع (`check5` ·
//               «٠٨٠ الضيّقة») · وتقريرُ مراجعةٍ خارجيّة · و`١١٠` الذي عاش
//               في `/tmp` ونصُّه غيرُ مُستردّ. وحراستُها تلزمها قائمةُ
//               أسماء، وهي تفشل مفتوحة.
//             🔴 وكُتبت «ثلاثةٌ» أوّلَ مرّة، فسقط `١١٠` — **وهو الشكلُ الذي
//               يحذّر منه هذا الرأسُ نفسُه بعد أسطر: قائمةٌ ناقصةٌ توهم
//               التمام.** ومَن كشفه سؤالٌ عن العدد، لا قراءةٌ للقائمة.
//             ⚠️ و`٠٠١–٠٤١` ليست منها: لا صفَّ لها أصلًا، فهي خارجَ الصنفين.
//   🔴 ولا يحرس : أنّ الحالة المكتوبة صادقة — ذاك تأكيدُ المالك، ولا يُقاس هنا.
//   🔴 ويفرض : عرفًا غيرَ مكتوبٍ في أيّ موضع — أنّ كلَّ سكربتٍ مُودَعٍ مرقَّم.
//             فـ`helpers.sql` بلا رقمٍ يُنتج رمزًا عدمًا فتسقط الحزمة، **ومن
//             يقع فيها لا يجد القاعدةَ التي خالفها.** ⇒ تُكتب القاعدةُ أو
//             يُرخى الشرط، ولا يُترك الحارسُ يشرّع بالسقوط.
//   ✅ وثغرةٌ **أُغلقت** (٢٧ آب ٢٠٢٦): كان توسيعُ المدى بالأرقام يزيد
//             التغطيةَ ولا ينقصها، فمرّ `076` و`078` بلا سطرِ حالةٍ حقيقيّ
//             تحت الصفّ `٠٧٣–٠٧٨` الذي يقول «غير مسجَّلة هنا».
//             **وأُغلقت بالترتيب الذي أُجّل به هذا الحارسُ أوّلَ مرّة:
//             كُتب الصفّان أوّلًا، ثمّ ضُيّق التوسيع** — فلم يُحمَّر على
//             ملفٍّ قائم. ⚠️ والمدى بالحروف يبقى مقصودًا.
//             🔴 وأثرُ الثغرة لم يكن على الحراسة وحدَها: الملفّان **سقطا من
//             دفعة الإضافة** لأنّ المُنتقيَ عدَّهما مغطَّيَين — **فكانت
//             خمسةً وخمسين وكان صوابُها سبعًا وخمسين.**
//
// **والرمزُ يُشتقّ من اسم الملفّ بقاعدةٍ مكتوبةٍ لا بقائمة**، وقد أخطأت
// نسختان قبلها: الأولى ابتلعت `095a2` في `095a` (فصار ١٦٧ ملفًّا بـ١٦٦ رمزًا)،
// والثانية عجزت عن `094b_a` و`080_1b`. والقاعدةُ الحاليّة مكتوبةٌ فوق كلّ
// تعبير، ومعها أمثلتُها.
const ROOT = path.join(__dirname, '..')
const SQL_DIR = path.join(ROOT, 'docs', 'sql')
const README = path.join(SQL_DIR, 'README.md')

// رمزُ الملفّ: ^(\d{3}[a-z]?\d?) ثمّ (_(\d+[a-z]?|[a-z]))? يتلوه _ أو . أو -
//   094_stock_lots ⟶ 094   ·   095a2_all… ⟶ 095a2   ·   094b_a_columns ⟶ 094b_a
//   080_1b_is…     ⟶ 080_1b ·   052a-survey… ⟶ 052a  ·   082_do_the… ⟶ 082
// 🔴 و«do» كلمةٌ لا لاحقة، فاللاحقةُ حرفٌ واحدٌ أو رقمٌ (وربّما بحرفٍ بعده).
const FILE_TOKEN = /^(\d{3}[a-z]?\d?)(_(?:\d+[a-z]?|[a-z]))?(?=[_.\-])/
const fileToken = (name) => {
  const m = FILE_TOKEN.exec(name)
  return m ? m[1] + (m[2] || '') : null
}

// رمزُ الصفّ: الخانةُ الأولى، بعد نزع التوكيد والقوسِ وما فيه ولاحقةِ «تتمّة»،
// وترجمةِ الأرقام والحروف العربيّة. ثمّ يُوسَّع المدى إلى أفراده.
const AR_DIGIT = { '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9' }
const AR_LETTER = { 'أ': 'a', 'ب': 'b', 'ج': 'c', 'د': 'd', 'ه': 'e', 'و': 'f', 'ز': 'g', 'ح': 'h' }
const ORDER = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h']

const rowToken = (cell) => {
  const s = (cell || '')
    .trim()
    .replace(/[`*]/g, '')
    .replace(/\([^)]*\)/g, '')
    .replace(/[–—-]\s*تتمّة\s*$/, '')
    .replace(/هـ/g, 'e')
    .trim()
  return s.split('').map((ch) => AR_DIGIT[ch] ?? AR_LETTER[ch] ?? ch).join('').trim()
}

// 096b/a–b ⟶ 096b_a · 096b_b   ·   049a–d ⟶ 049a…049d   ·   053–063 ⟶ 053…063
const expand = (token) => {
  let m = /^(\d{3}[a-z]?)\/([a-z])[–—-]([a-z])$/.exec(token)
  if (m) {
    const from = ORDER.indexOf(m[2])
    const to = ORDER.indexOf(m[3])
    if (from >= 0 && to >= from) return ORDER.slice(from, to + 1).map((c) => `${m[1]}_${c}`)
  }
  m = /^(\d{3}[a-z]?)\/([a-z])$/.exec(token)
  if (m) return [`${m[1]}_${m[2]}`]
  m = /^(\d{3})([a-z])[–—-]([a-z])$/.exec(token)
  if (m) {
    const from = ORDER.indexOf(m[2])
    const to = ORDER.indexOf(m[3])
    if (from >= 0 && to >= from) return ORDER.slice(from, to + 1).map((c) => m[1] + c)
  }
  // 🔴 ومدًى **بالأرقام** (`٠٧٣–٠٧٨`) لا يُوسَّع ولا يُعَدّ تغطية: صفوفُه
  //    عندنا صفوفُ **إعلانِ غياب** («غير مسجَّلة هنا») — فتوسيعُه يجعل
  //    الحارسَ يقرأ إعلانَ الغياب تغطيةً. وقد فعل: `076` و`078` مرّا بلا
  //    سطرِ حالةٍ حقيقيّ حتّى كُتب لهما صفّان (٢٧ آب ٢٠٢٦).
  //    ⚠️ والمدى **بالحروف** يبقى: `٠٩٤ب/أ–هـ` صفٌّ واحدٌ لخمسة ملفّاتٍ عمدًا.
  return [token]
}

// ⚠️ الترويسةُ تُقرأ بنصّها، وترويسةٌ ثانيةٌ **تُنهي** الجدولَ الأوّل ولا
// تُتخطّى — وتخطّيها عدّ ثمانيةَ صفوفٍ مرّتين حين قِيست أوّلَ مرّة.
const HEADER = '| # | ما يفعله | الحالة | الدليل الذي أكّده المالك |'

const statusRowCells = () => {
  const lines = fs.readFileSync(README, 'utf8').replace(/\r/g, '').split('\n')
  const heads = []
  lines.forEach((line, i) => { if (line.trim() === HEADER) heads.push(i) })
  const cells = []
  for (let k = 0; k < heads.length; k += 1) {
    const stop = k + 1 < heads.length ? heads[k + 1] : lines.length
    for (let j = heads[k] + 2; j < stop; j += 1) {
      if (lines[j].trim() === '') continue
      if (!lines[j].startsWith('|')) break
      if (/^\|-/.test(lines[j].trim())) continue
      cells.push(lines[j].split('|')[1])
    }
  }
  return { cells, heads }
}

describe('كلُّ سكربتٍ مُودَعٍ له سطرُ حالة', () => {
  const files = fs.readdirSync(SQL_DIR).filter((name) => name.endsWith('.sql'))

  // ⚠️ حارسُ الحارس: مجلَّدٌ يُنقل أو ترويسةٌ تُعاد صياغتُها يجعلان الفحصَ
  // يمرّ على العدم. فيقول ذلك بدل أن ينجح صامتًا (البند ١ج).
  it('يقرأ سكربتاتٍ فعلًا، لا مجلَّدًا فارغًا', () => {
    expect(files.length).toBeGreaterThan(100)
  })

  it('يجد جداولَ الحالة بترويستها، لا يمرّ عليها', () => {
    expect(statusRowCells().heads.length).toBeGreaterThan(0)
  })

  it('يُنتج رمزًا لكلّ ملفّ، ولا رمزَ لملفَّين', () => {
    const tokens = files.map(fileToken)
    expect(tokens.filter((t) => t === null)).toEqual([])
    expect(new Set(tokens).size).toBe(files.length)
  })

  it('ولا ملفَّ بلا سطرِ حالة', () => {
    const covered = new Set()
    for (const cell of statusRowCells().cells) {
      for (const token of expand(rowToken(cell))) covered.add(token)
    }
    const bare = files.filter((name) => !covered.has(fileToken(name)))
    // 🔴 تُسمّى الملفّاتُ الساقطة، فالفشلُ يقول «هذا الملفّ» لا «توقّعتُ صفرًا».
    expect(bare).toEqual([])
  })
})
