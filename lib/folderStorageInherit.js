import { ALL_STORAGES } from './storageScope'
import { isPassThroughFolder } from './folderStorageScope'
import { parentOptionsFor } from './categoryVisibility'

// أيُّ مستودعٍ يأخذه مجلّدٌ جديد — بلا سؤالٍ وبلا حقل.
//
// 🔴 قرارُ المالك: لا خانةَ اختيارِ مستودعٍ في نافذة المجلّد إطلاقًا. المستودعُ
// **يُشتقّ** من السياق الذي يُنشأ فيه المجلّد، ومتى غاب السياقُ يُمنع الإنشاء
// بدل أن يُخمَّن.
//
//   أبٌ موجود        ⟵ مستودعُ الأب، ومهما كان المختارُ أعلى الشاشة
//   بلا أب، عدسةٌ    ⟵ المستودعُ المختار
//     على مستودعٍ بعينه
//   بلا أب، «كل      ⟵ لا شيء. ولا سياقَ يُؤخذ منه، فلا تخمين.
//     المستودعات»
//
// ⚠️ والأبُ يسبق العدسةَ لا العكس، وهذا هو الترتيبُ الذي يمنع شجرةً مكسورة:
// مجلّدٌ فرعيٌّ في مستودعٍ غير مستودع أبيه يظهر تحت مستودعه ويختفي تحت مستودع
// أبيه — أي يصير أبوه «عمودًا فقريًّا» لمجلّدٍ لا يخصّه، وهي الحالةُ التي
// يحرسها lib/folderStorageScope.test.js من الجهة الأخرى.

// ⚠️ رمزٌ صريحٌ لـ«ما في سياق»، لا `null` عاريةً — لأن `null` هنا ستُقرأ
// «مجلّدٌ غيرُ مُسنَد»، وهي حالةٌ أخرى تمامًا: تلك بياناتٌ قديمةٌ مشروعة، وهذه
// رفضٌ للإنشاء. القيمةُ نفسُها والمعنيان مختلفان، فيُسمَّى المعنى.
// ⚠️ **صار جمعًا، والسنتينل راح معه.** المجلّدُ يمكن أن يكون في أكثر من
// مستودع، فالجوابُ **قائمةٌ** لا قيمة — و«ما في سياق» صارت **القائمةَ الفارغة**
// بدل رمزٍ يعني `null` ويُخلَط بـ«غيرِ مربوط». الفراغُ يقول عن نفسه ولا يحتاج
// اسمًا.
export const NO_CONTEXT = []

// 🔴 الابنُ يأخذ **كلَّ** روابط أبيه — قرارُ المالك، والحجّةُ بنيويّةٌ لا ذوقيّة.
//
// البديلُ (رابطُ العدسة وحدَها) **يجعل الأبَ عقدةً معلَّقةً فورًا في باقي
// مستودعاته** — أي أن الإنشاءَ العاديّ يُنتج بالضبط الحالةَ الشاذّة التي بُني
// `isPassThroughFolder` ليستوعبها لا ليولّدها. ومع «كلّ الروابط» تبقى روابطُ
// الابن ⊆ روابطَ الأب دائمًا، **فلا يمكن أن يولد معلَّقًا.**
//
// ⚠️ **والاعتراضُ الوجيه مسجَّل: هذا افتراضٌ متساهل** — ثلاثةُ روابطَ بضغطة.
// وما يحسمه أن **غيابَ الرابط غيرُ مرئيّ** (المجلّدُ غائبٌ ولا شيء يقول لماذا)
// **والرابطَ الزائدَ مرئيٌّ ويُنزع بنقرة** من نافذة المستودع — وقبل أن تتحرّك
// بضاعة، النزعُ مسموحٌ بلا قيد. **فالافتراضُ يفشل نحو المرئيّ.**
export function storagesForNewFolder({ parent = null, lensStorageId = null, links = [] } = {}) {
  // الأبُ أوّلًا ودائمًا — الشجرةُ هي التي تقرّر، لا ما يصادف أن يكون مختارًا.
  if (parent) {
    const inherited = []
    for (const link of links || []) {
      if (link.category_id === parent.id) inherited.push(link.storage_id)
    }
    return [...new Set(inherited)]
  }
  if (!lensStorageId || lensStorageId === ALL_STORAGES) return []
  return [lensStorageId]
}

// 🔴 هل يُسمح بإنشاء مجلّدٍ الآن — **مشتقٌّ من الجواب نفسِه لا قائمةٌ ثانية.**
//
// طلبُ المالك حرفيًّا: «لما كل المستودعات هو المختار: زرّ إضافة فولدر ينعطّل —
// ما في سياق تلقائي نقدر ناخده منه، فما منخمّن».
//
// ⚠️ وحرفيّةُ الجملة وسببُها يفترقان في حالةٍ واحدة، وهي واقعة: «كل
// المستودعات» **مع مجلّدٍ مختارٍ مُسنَد**. الحرفيّةُ تقول امنع؛ والسببُ —
// «ما في سياق» — لا ينطبق، لأن الأبَ سياقٌ كاملٌ ومذكورٌ في القاعدة التي
// قبلها بسطر («بغضّ النظر شو مختار بأعلى الشاشة»).
//
// ⇒ فالزرُّ يُمنع حين **لا يوجد جواب**، لا حين تكون العدسةُ واسعة. جملةٌ واحدة
// تُنتج الحالتين: العدسةُ الواسعة بلا مجلّدٍ مختار تُعطي `NO_CONTEXT` فيُمنع،
// والعدسةُ الواسعة مع أبٍ مُسنَد تُعطي مستودعَ الأب فيُسمح.
//
// ⚠️ والأهمّ أنه **مشتقٌّ**: الزرُّ والكتابةُ يقرآن نفسَ الدالّة، فلا يمكن أن
// يختلفا. شرطٌ منفصلٌ على الزرّ هو القائمةُ الثانية التي تتباعد يومًا —
// وهذا المشروع دفع ثمنَها أكثر من مرّة.
export function canCreateFolder(context) {
  return storagesForNewFolder(context).length > 0
}

// 🔴 أيُّ مجلّدٍ يصلح أبًا — والمستودعُ يضيّقها **عند الإنشاء وحدَه.**
//
// المجلّدُ الجديد يأخذ مستودعَ أبيه. فعرضُ أبٍ من مستودعٍ آخر ونحن واقفون على
// هذا يعرض مجلّدًا **يولد غيرَ مرئيّ**: يُنشأ من شجرة التجميل، ويُسنَد للشعر،
// ويختفي من الشاشة لحظةَ حفظه. وهي نفسُ علّة الضغط على عقدةٍ معلَّقة من بابٍ
// آخر — والثابتةُ التي تُحفظ جملةٌ واحدة:
//
//   **كلُّ مجلّدٍ يُنشأ يظهر في الشجرة التي أُنشئ منها.**
//
// ⚠️ **وعند الإنشاء وحدَه، والسببُ عطلٌ لا تفضيل.** التعديلُ يفتح على
// `parent_id` القائم، **وهو قد يكون مجلّدًا في مستودعٍ آخر** — تعشيشٌ قديم، أو
// من ٠٨٦. فتضييقُ القائمة هناك يُخرج الأبَ الحاليَّ من الخيارات، فتسقط القائمةُ
// المنسدلة إلى «بلا»، **ويُعيد الحفظُ المجلّدَ إلى الجذر بلا أن يطلب ذلك أحد.**
// أمّا عند الإنشاء فالأبُ الابتدائيّ هو المجلّدُ المختار، وهو مضمونُ الانتماء
// لهذا المستودع، فلا يغيب عن القائمة أبدًا.
//
// ⚠️ ويُبنى فوق `parentOptionsFor` لا بدلًا منها: تلك تمنع الدورة — أن يصير
// المجلّدُ ابنًا لحفيده — وهي القاعدة التي كُتبت مرّةً واحدةً عمدًا بعد أن
// نُسخت ثلاث مرّاتٍ مختصرةً. **والمستودعُ يضيف تضييقًا، ولا يستبدل ذاك.**
export function parentChoicesForFolder({ category = null, categories, lensStorageId = null, links = [] } = {}) {
  const options = parentOptionsFor(category, categories)
  if (category) return options
  return options.filter((c) => !isPassThroughFolder(c, lensStorageId, links))
}
